// ============================================================
// ★★ 最遠景の「景観」—— 島さんの持ち場 ★★
// ============================================================
//
//   島さん（2026-08-13）:
//   > 現在の問題は「山の絵の品質」ではなく、最遠景が
//   > **「ランダムな部品の集合」に見えている**ことです。
//   > 最遠景は「物体」ではなく **「景観」** として設計してください。
//
//   ★★だから、ここには「山の絵」がありません。**土地の形（高さの線）**だけがあります。
//
// ■ 役割を2つに分けています（★片方だけにしないこと）
//
//     ① **連続地形** …… ★**景観の土台**。端から端まで途切れずに続く土地
//     ② **巨大ランドマーク** …… ★**景観の特徴**。ごくまれに現れて「景色が変わった」と感じさせる
//
//   ★連続地形だけだと**単調な波形**になり、「ここに何があるのか」という発見が消えます。
//   ★巨大部品だけだと**「アイコンが並んでいる」**問題に戻ります。
//
// ■ ★★描く順番（島さんの指定。ここを入れ替えないこと）
//
//     空 → 連続地形A（薄い山並み） → **ランドマーク** → 連続地形B（少し濃い丘陵）
//        → 遠景の部品 → 中景 → 前景 → 地面 → プレイヤー
//
//   ★**ランドマークを「帯A のあと・帯B の前」に描く**のが、この設計のいちばん大事なところ。
//     あとから描く**地形B**が、**ランドマークの下部を自然に隠してくれる**（→ ③の節）
//
//   ★★2026-08-13、ここの説明が**実物と食い違っていた**（「ランドマークをいちばん先に描く」
//     と書いてあったが、実物は `js/ollie.js` の `draw()` で **帯A → ランドマーク → 帯B**）。
//     ★この説明を信じて順番を入れ替えると、**ランドマークが緑の山並みの裏に回って消えます**
//     （帯Aの平均の高さ 38.8 ＞ ランドマークの peak 34〜46 なので、ほとんど隠れてしまう）。
//     ★実装は変えていない。説明だけを実物に合わせた。**正は `js/ollie.js` の `draw()`**
//
// ■ 島さんが触るのは、下の3つの表だけ
//
//     `SHAPES`    …… 地形のかたち（数字の列）
//     `BANDS`     …… 帯（どの速さで流れる土地か）
//     `LANDMARKS` …… 巨大ランドマーク
//
// ■ ★★地形のデータをどこにも溜めていません
//
//   「種」と「いまいる場所」だけから、**その場で計算**しています。
//   だから **無限に続き・戻れば同じ・何万メートル進んでも重くならない**。
//   ★**配列に地形を貯めた瞬間に、この性質は全部失われます。そこを崩さないこと。**
// ============================================================
(function (global) {
	"use strict";

	var WD = global.DotWorld;
	var PAL = global.DotPalette;

	// ============================================================
	// ■■■ ① 地形のかたち —— ★島さんの持ち場 ■■■
	// ============================================================
	//
	//   数字は **「その区画の中での高さの割合」**（0 = 土台と同じ / 1 = いちばん高い）。
	//   ★★**両端は必ず 0 にしてください。**
	//
	//   ■ なぜ両端が 0 なのか（★ここが崩れると継ぎ目に段差が出ます）
	//
	//     高さ = **土台**（となりの区画へなめらかに繋ぐ線）＋ **かたち**（この表）
	//
	//     土台はもともと連続しているので、**かたちが両端で 0 なら継ぎ目で必ず一致します**。
	//     ★つまり「段差が出ないか心配する」のではなく、**構造として段差が作れない**。
	//
	//   ★数字の数は自由（多いほど細かい形が描けます）。間はなめらかに繋ぎます
	var SHAPES = [
		{ name: "ギザギザした山脈", h: [0, .15, .5, .95, .6, .3, .55, 1, .7, .4, .2, .45, .25, 0] },
		{ name: "丸い丘陵",       h: [0, .3, .7, .95, 1, .85, .5, .35, .6, .8, .7, .4, .15, 0] },
		{ name: "平らな台地",     h: [0, .1, .9, 1, 1, 1, .95, 1, 1, .4, .15, .1, .05, 0] },
		{ name: "谷",            h: [0, .5, .8, .55, .15, .05, .1, .3, .7, .9, .6, .25, .1, 0] },
		{ name: "なだらかな地形", h: [0, .2, .35, .45, .4, .3, .35, .5, .45, .3, .2, .1, .05, 0] }
	];

	// ============================================================
	// ■■■ ② 帯（連続地形）—— ★島さんの持ち場 ■■■
	// ============================================================
	//
	//   name   … 名前（テストのメッセージに出るだけ）
	//   speed  … 流れる速さ。★地面を 1 とする。小さいほど遠くに見える
	//   segW   … 1区画の幅（ドット）。★**帯ごとに違う値にしてください**。
	//            揃えると継ぎ目が縦に並んで、周期が見破られます
	//   peak   … その帯のいちばん高いところ（ドット）。★ここを変えれば山の高さが変わる
	//   edges  … 継ぎ目の高さの候補。★ここから種で1つ選ばれる
	//   color  … 色（`js/palette.js` の文字）
	//
	// ■ ★★色の並びは「**空より明るい遠山 ＋ 空より暗い手前**」
	//
	//     帯A（最奥）      暗い緑 #008751（明るさ17.9）… ★空より**明るい**＝大気に霞んだ遠山
	//     ランドマーク     炭     #3a3839（4.0）        … ★空より暗い＝巨大な影
	//     帯B（手前）      濃紺   #1d2b53（2.6）        … ★いちばん暗い＝手前の丘陵
	//
	//   ★★2026-08-13、25色化のときに「奥ほど空に近い明るさ」という理屈だけで
	//     **色を選び直したら、画面が重く沈んで失敗しました**
	//     （帯Aを炭にしたら、暗い塊が画面の上半分を占め、手前の緑が明るく浮いた）。
	//     → **35色のときと同じ色に戻しました**（番号だけ 25色版に付け替え）。
	//     ★これが島さんに確認5点をOKしてもらった見た目です。
	//
	//   ★★教訓: 空が暗い色（藍）のときは、**遠い山を空より明るく**するほうが自然。
	//     「奥ほど空に近い」を明るさの数字だけで当てはめないこと
	//
	//   ★★2026-08-13、島さんの指定で数値を詰めました（液晶240×160・地面の基準行は124）:
	//     ・帯B の起伏を大きくした（`peak` 16→22 / `edges` の幅を広げた）
	//       ★`edges` の幅を広げるのがいちばん効きます（継ぎ目ごとの土台の差＝大きな起伏）
	//     ・帯A の裾を上げた（`edges` 6→10 から）ので、**帯Bに隠れず奥の山並みが上に出る**
	//     ★帯Aの最小(10) < 帯Bの最大(38) は保っています
	//       ＝ 場所によっては**手前の丘が奥の山を隠す**（そのほうが景色に変化が出る）
	var BANDS = [
		{ name: "山並み（薄い）",   speed: 0.05, segW: 160, peak: 32, edges: [14, 24, 34], color: "c" },
		{ name: "丘陵（少し濃い）", speed: 0.09, segW: 120, peak: 22, edges: [0, 6, 12],   color: "a" }
	];
	//   ★★この2行の数字をこう決めた理由（2026-08-13。★画面を見ながら3回直した）:
	//
	//     1回目 帯B `edges` [2,9,16] …… ★**帯Bが帯Aを隠しすぎ**、奥の山並みが
	//            「紺の上の細い緑の縁」にしか見えなかった
	//     2回目 帯B `edges` [0,6,12] に下げた …… まだ**高さの差が平均12ドット**で細かった
	//     3回目 ★**帯Aを高くした**（`peak` 26→32 / `edges` を [14,24,34] へ）
	//            → 帯Aの平均が約40、帯Bが約17 ＝ **23ドットの差**。緑の山並みが2倍見える
	//
	//   ★★帯B の起伏（`peak` 22）は1回も下げていません（島さんの①「起伏を大きく」を守る）。
	//     直したのは**位置**（`edges`）と**帯Aの大きさ**だけ。
	//   ★帯Aの最大は66 → 画面の58行目まで。空は画面の1/3ほど残ります

	// ============================================================
	// ■■■ ③ 巨大ランドマーク —— ★島さんの持ち場 ■■■
	// ============================================================
	//
	//   ★★これは「部品」ではなく **「景観のランドマーク」**。
	//     目的は背景を賑やかにすることではなく、
	//     **進んだときに「景色が変わった」と感じてもらうこと**です。
	//
	//   w    … 横幅（ドット）。★液晶の幅は240。**それに対して十分大きく**（100〜300）
	//   peak … いちばん高いところ（ドット）。★帯より高いので、山並みの上に頭を出します
	//   h    … かたち（上の SHAPES と同じ書き方。★両端 0）
	//
	//   ★★まず3種だけです（島さんの指定）。**増やすのは、この構造が「景観」に見えると
	//     確認できてから。**
	//
	// ■■ ★★下部は地形が隠してくれる（マスク方式）
	//
	//   島さん（2026-08-13）:
	//   > ランドマークの下端は、配置地点の連続地形Bより十分下まで伸ばしてよい。
	//   > その後に連続地形Bを描画することで、地形Bがランドマーク下部を自然にマスクする。
	//
	//   → ★**下端は液晶の下まで伸ばします**（`fillBelow` がそう塗ります）。
	//     あとから**地形B**と地面が上から重なるので、**足元が自然に隠れます**
	//     （★地形A は**先に**描くので、隠す側ではありません。ランドマークは帯Aの手前に立つ）。
	//
	//   ★★これのおかげで **「浮く」「食い込む」が構造的に起きません**。
	//     「足元をどの高さに合わせるか」という難しい判断そのものが消えます。
	//
	//   ★★**やってはいけないこと**: 場所ごとに「地形Bの高さ ＋ ランドマークの高さ」を足すこと。
	//     それをすると**地形の凹凸がランドマークの輪郭に乗り**、
	//     「地形と同じ形をした山が重なっている」状態になります（島さんが禁じたもの）。
	//     → ★**同じランドマークは、地形がどう変わっても輪郭が同じ**。テストが見張っています
	//   ★★2026-08-13、島さんの指定で数値を詰めました。**大事な直しが2つ**:
	//
	//     ① ★★**`peak` を帯Bの最大(38)より高くした**（40→46 / 28→40 / 22→34）
	//        ★前は 卓状台地(28) と 巨大な森(22) が**帯Bより低く**、
	//          **丘陵が高い場所ではランドマークが丸ごと埋まって見えなくなっていました**。
	//          「ランドマークが出ているのに気づけない」原因がこれでした
	//        ★どれも帯Aの最大(52)は超えません＝空を覆いすぎない
	//
	//     ② ★★**横幅を液晶の幅(240)より小さくした**（200→170 / 240→200）
	//        ★巨大な森は幅240＝**画面幅ぴったりで画面を横切り、「壁」に見えていました**。
	//          両側に空が残るようにすると、「向こうにある大きなもの」に見えます
	var LANDMARKS = [
		{ name: "巨大な岩山", w: 140, peak: 46,
			h: [0, .1, .25, .5, .8, .95, 1, .9, .7, .55, .45, .3, .15, .05, 0] },
		{ name: "卓状台地",   w: 170, peak: 40,
			h: [0, .05, .35, .8, .96, 1, 1, 1, 1, .98, .9, .5, .2, .06, 0] },
		{ name: "巨大な森",   w: 200, peak: 34,
			h: [0, .35, .6, .5, .7, .55, .75, .6, .8, .65, .5, .6, .35, .15, 0] }
		// ★次の候補（確認が済んでから足す）: 雪山（頂を白くする）/ 遠い街
	];

	// ★ランドマークの調整値
	var LM_SPEED  = 0.05;   // ★流れる速さ。★帯Aと同じ＝同じ距離帯にある（ずれない）
	var LM_SLOT   = 1024;   // ★世界をこの幅で区切り、**1枠に最大1つ**だけ置く
	var LM_PAD    = 350;    // ★枠の端から空ける幅。★**中心間距離 = PAD×2 = 700ドット**を保証する
	var LM_CHANCE = 0.55;   // ★その枠に出るかどうかの割合。★低いほど「まれ」になる
	// ★色。★帯Aの**手前**に立つので、**帯Aより濃く・帯Bより薄く**しています
	//   （明るさ: 帯A 17.9 → ★ランドマーク 4.0 → 帯B 2.6）
	var LM_COLOR  = "5";    // 5 = 炭（★空より暗い＝巨大な影として見せる）

	// ============================================================
	// ここから下は仕組み（ふつうは開かなくてよい）
	// ============================================================

	var GROUND = 0;   // 地面の基準行（`setup` で受け取る）
	var LCD_H  = 0;   // 液晶の高さ

	// なめらかに繋ぐ（0→1 を、両端でゆるやかになる曲線にする）
	function smooth(t) { return (1 - Math.cos(t * Math.PI)) / 2; }

	// 数字の列を「0〜1 の位置」で読む（間はなめらかに繋ぐ）
	function shapeValue(h, t) {
		if (t <= 0) return h[0];
		var n = h.length - 1;
		if (t >= 1) return h[n];
		var p = t * n, i = Math.floor(p);
		return h[i] + (h[i + 1] - h[i]) * smooth(p - i);
	}

	function seed() { return WD.getSeed(); }

	// ------------------------------------------------------------
	// ■ 連続地形 —— 「土台」＋「かたち」
	// ------------------------------------------------------------
	//   ★どちらも **区画番号 k と種だけ**で決まる（前の区画を見に行かない）。
	//     だから無限に続き、戻れば同じで、何万メートル進んでも重くならない
	function edgeAt(bi, k) {
		var B = BANDS[bi];
		var r = WD.rand(k, seed() + 1301 + bi * 97);
		return B.edges[Math.min(B.edges.length - 1, Math.floor(r * B.edges.length))];
	}

	function shapeAt(bi, k) {
		var r = WD.rand(k, seed() + 2603 + bi * 89);
		return Math.min(SHAPES.length - 1, Math.floor(r * SHAPES.length));
	}

	// その帯の、位置 x での高さ（★基準線から何ドット上か）
	function bandHeightAt(bi, x) {
		var B = BANDS[bi];
		var k = Math.floor(x / B.segW);
		var t = (x - k * B.segW) / B.segW;
		// 土台 …… 区画の左端の高さ → 右端の高さ へ、なめらかに
		var base = edgeAt(bi, k) + (edgeAt(bi, k + 1) - edgeAt(bi, k)) * smooth(t);
		// かたち …… 両端で 0 なので、土台の連続性を壊さない
		var form = shapeValue(SHAPES[shapeAt(bi, k)].h, t) * B.peak;
		return Math.round(base + form);
	}

	// ------------------------------------------------------------
	// ■ 巨大ランドマーク
	// ------------------------------------------------------------
	//   枠 k に置くもの（無ければ null）。★k と種だけで決まる
	function slotAt(k) {
		if (WD.rand(k, seed() + 4021) >= LM_CHANCE) return null;
		var r = WD.rand(k, seed() + 5023);
		var lm = LANDMARKS[Math.min(LANDMARKS.length - 1, Math.floor(r * LANDMARKS.length))];
		// ★中心は枠の [PAD, SLOT-PAD] の中だけ。→ となりの枠と最悪でも PAD×2 離れる
		var cx = k * LM_SLOT + LM_PAD +
			WD.rand(k, seed() + 6029) * (LM_SLOT - LM_PAD * 2);
		return { k: k, lm: lm, cx: Math.round(cx) };
	}

	// 位置 x での「ランドマークの高さ」（無ければ 0）
	//   ★★ここで地形の高さを足さないこと（輪郭は地形から完全に独立）
	function lmHeightAt(x) {
		var wide = 0;
		for (var i = 0; i < LANDMARKS.length; i++) {
			if (LANDMARKS[i].w > wide) wide = LANDMARKS[i].w;
		}
		var half = Math.ceil(wide / 2) + 2;
		var kFrom = Math.floor((x - half) / LM_SLOT), kTo = Math.floor((x + half) / LM_SLOT);
		var best = 0;
		for (var k = kFrom; k <= kTo; k++) {
			var s = slotAt(k);
			if (!s) continue;
			var w2 = s.lm.w / 2;
			if (x < s.cx - w2 || x > s.cx + w2) continue;
			var t = (x - (s.cx - w2)) / s.lm.w;
			var h = Math.round(shapeValue(s.lm.h, t) * s.lm.peak);
			if (h > best) best = h;
		}
		return best;
	}

	// ------------------------------------------------------------
	// ■ 外に出す窓口
	// ------------------------------------------------------------
	global.DotSkyline = {
		SHAPES: SHAPES, BANDS: BANDS, LANDMARKS: LANDMARKS,
		LM_SPEED: LM_SPEED, LM_SLOT: LM_SLOT, LM_PAD: LM_PAD,
		LM_CHANCE: LM_CHANCE, LM_COLOR: LM_COLOR,

		// 液晶の大きさと、地面の基準行を教えてもらう
		setup: function (lcdH, groundRow) { LCD_H = lcdH; GROUND = groundRow; },

		// その帯の高さ／ランドマークの高さ（★基準線から何ドット上か）
		bandHeightAt: bandHeightAt,
		lmHeightAt: lmHeightAt,
		slotAt: slotAt,
		edgeAt: edgeAt,
		shapeAt: shapeAt,
		shapeValue: shapeValue,

		// 色の番号（`js/palette.js` の文字 → 番号）
		colorIndexOf: function (ch) { return PAL.indexOfChar(ch); },

		// ★★描くときに使う「その列の上端の行」
		//   ★液晶の外（＝何も無い）ときは LCD_H を返す。`fillBelow` がそこを塗らない
		bandRowAt: function (bi, worldX, col) {
			var x = Math.round(worldX * BANDS[bi].speed) + col;
			return GROUND - bandHeightAt(bi, x);
		},
		lmRowAt: function (worldX, col) {
			var x = Math.round(worldX * LM_SPEED) + col;
			var h = lmHeightAt(x);
			return h > 0 ? (GROUND - h) : LCD_H;      // 0 なら「何も無い」
		}
	};
})(typeof window !== "undefined" ? window : globalThis);
