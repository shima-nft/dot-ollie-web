	// ★★★その帯が実際に届く「いちばん高いところ」（2026-08-21）
	//
	//   ★`peak` は**数式の形のための宣言値**です。
	//   ★★島さんの絵は、その宣言より**高くなることがあります**
	//     （★下敷きには余白が10ドットあり、島さんはそこまで使ってよい）。
	//   → ★★**絵があるときは、絵のいちばん高いところを採る**。
	//     ★これで、島さんが絵を描き替えても**宣言と実体がずれません**
	//     （★実際に丘の絵が `peak 22` を1ドット超えて、`test/skyline.test.js` が止めた）
	// ★★★★2026-08-27、島さんが描いた「終わり方」の絵を引く（→ `js/end-shape-art.js`）
	//   ★`style` … "slope"（なだらか）/ "cliff"（崖）。→ `js/regions.js` の `endStyleAt`
	//   ★★絵が無ければ null（★そのときは数式で終わります ＝ 描く前でも動く）
	// ★★★★その帯の「海面の高さ」（2026-08-27 島さんの指定）
	//
	//   > 島さん「丘陸の海面高さを丘陸の中で一番低い谷の高さに揃えてください。
	//   >   でないと不自然。」
	//
	//   ★★**その帯のいちばん低い谷**（＝ `edges` のいちばん小さい値）に揃えます。
	//     ★これより高くすると、★★★**まだ陸なのに谷だけ海になり**、
	//       山あいに水が入り込んだように見えます（★島さんの言う「不自然」）。
	//   ★★数字を直書きしません（★`edges` を変えたら、海面も自動で追従します）。
	//   ★`sea.level` を書けば、その値が優先されます
	function seaLevelOf(B) {
		if (!B.sea) return 0;
		if (B.sea.level !== undefined) return B.sea.level;
		var valley = Math.min.apply(null, B.edges);
		// ★★★★2026-08-27、**地面の起伏に負けない高さ**まで持ち上げます（島さんの選択A）。
		//
		//   ★★丘陵の谷は 8 ですが、★地面は基準線から**±11**動きます（→ `js/world.js` の `AMP`）。
		//     ★★★だから 8 のままだと、**丘陵の海が地面に埋もれて画面に出ませんでした**
		//       （★実測: 内部では167列あるのに、画面には0列）。
		//   → ★「谷の高さ」と「地面の起伏＋1」の**高いほう**にします。
		//     ★★遠山（34）は変わりません。★丘陵だけ 8 → 12 になります。
		//   ★★★数字は直書きしません（★`AMP` を変えたら、ここも自動で追従します）
		var floor = (WD.AMP || 0) + 1;
		return Math.max(valley, floor);
	}

	function endArtOf(B, style) {
		var A = global.DotEndShapeArt;
		if (!A || !B.artPrefix) return null;
		return A[B.artPrefix + "end-" + style] || null;
	}

	function peakOf(B) {
		if (!B.useArt) return B.peak;
		var max = B.peak;
		for (var i = 0; i < SHAPES.length; i++) {
			var A = artOf(SHAPES[i], B);
			if (A && A.PEAK > max) max = A.PEAK;
		}
		return max;
	}

	// ★★その帯・その形に島さんの絵があれば返す（★無ければ null ＝ 数式のかたちを使う）
	//   ★★★帯ごとに絵が違う（遠山は `yama-*` / 丘は `band1-*`）
	function artOf(sh, B) {
		var ART = global.DotShapeArt;
		if (!sh || !B || !B.useArt || !ART) return null;
		var name = (B.artPrefix || "") + (sh.key || "");
		return ART[name] || null;
	}

	// なめらかに繋ぐ（0→1 を、両端でゆるやかになる曲線にする）
	function smooth(t) { return (1 - Math.cos(t * Math.PI)) / 2; }

	// 数字の列を「0〜1 の位置」で読む（間はなめらかに繋ぐ）
	function shapeValue(h, t) {
		if (t <= 0) return h[0];
		var n = h.length - 1;
		if (t >= 1) return h[n];
		var p = t * n, i = Math.floor(p);
		return h[i] + (h[i + 1] - h[i]) * smooth(p - i);
	}

	function seed() { return WD.getSeed(); }

	// ------------------------------------------------------------
	// ■ 連続地形 —— 「土台」＋「かたち」
	// ------------------------------------------------------------
	//   ★どちらも **区画番号 k と種だけ**で決まる（前の区画を見に行かない）。
	//     だから無限に続き、戻れば同じで、何万メートル進んでも重くならない
	function edgeAt(bi, k) {
		var B = BANDS[bi];
		var r = WD.rand(k, seed() + 1301 + bi * 97);
		return B.edges[Math.min(B.edges.length - 1, Math.floor(r * B.edges.length))];
	}

	function shapeAt(bi, k) {
		var r = WD.rand(k, seed() + 2603 + bi * 89);
		return Math.min(SHAPES.length - 1, Math.floor(r * SHAPES.length));
	}

	// その帯の、位置 x での高さ（★基準線から何ドット上か）
	function bandHeightAt(bi, x) {
		var B = BANDS[bi];
		var k = Math.floor(x / B.segW);
		var t = (x - k * B.segW) / B.segW;
		// 土台 …… 区画の左端の高さ → 右端の高さ へ、なめらかに
		var base = edgeAt(bi, k) + (edgeAt(bi, k + 1) - edgeAt(bi, k)) * smooth(t);
		// かたち …… 両端で 0 なので、土台の連続性を壊さない
		//   ★★★島さんの絵があれば、そのかたちを使う（→ `js/shape-art.js`）
		var sh = SHAPES[shapeAt(bi, k)];
		var A = artOf(sh, B);                     // ★絵を使うのは `useArt` を書いた帯だけ
		var form = A ? A.FORM[Math.min(A.W - 1, Math.floor(t * A.W))]
		             : shapeValue(sh.h, t) * B.peak;
		return Math.round(base + form);
	}

	// ------------------------------------------------------------
	// ■ 巨大ランドマーク
	// ------------------------------------------------------------
	//   枠 k に置くもの（無ければ null）。★k と種だけで決まる
	function slotAt(k) {
		if (WD.rand(k, seed() + 4021) >= LM_CHANCE) return null;
		var r = WD.rand(k, seed() + 5023);
		var lm = LANDMARKS[Math.min(LANDMARKS.length - 1, Math.floor(r * LANDMARKS.length))];
		// ★中心は枠の [PAD, SLOT-PAD] の中だけ。→ となりの枠と最悪でも PAD×2 離れる
		var cx = k * LM_SLOT + LM_PAD +
			WD.rand(k, seed() + 6029) * (LM_SLOT - LM_PAD * 2);
		cx = Math.round(cx);
		// ============================================================
		// ★★★★2026-08-27、**海ではランドマークを置きません**（島さんの指定）
		// ============================================================
		//
		//   > 島さん「なだらかに終わるのではなくそもそも海では出現０にする。」
		//
		//   ★★**幅のぶんは見ます**（★中心が陸でも、端が海にかかるものは置かない）。
		//     ★★★見るのは**その場所の地域だけ**（★島さん「厳密には海で出現率を０ね」）。
		//   ★★★ここで「置かない」ので、★**目の前でランドマークが消えることは起きません**。
		//   ★どの地域で置かないかは `js/regions.js` の `landmark: 0`
		var RG = global.DotRegions;
		if (RG && RG.landmarkAt) {
			var half = lm.w / 2;
			for (var e = -1; e <= 1; e++) {
				if (RG.landmarkAt((cx + e * half) / LM_SPEED) === 0) return null;
			}
		}
		return { k: k, lm: lm, cx: cx };
	}

	// 位置 x での「ランドマークの高さ」（無ければ 0）
	//   ★★ここで地形の高さを足さないこと（輪郭は地形から完全に独立）
	function lmHeightAt(x) {
		var wide = 0;
		for (var i = 0; i < LANDMARKS.length; i++) {
			if (LANDMARKS[i].w > wide) wide = LANDMARKS[i].w;
		}
		var half = Math.ceil(wide / 2) + 2;
		var kFrom = Math.floor((x - half) / LM_SLOT), kTo = Math.floor((x + half) / LM_SLOT);
		var best = 0;
		for (var k = kFrom; k <= kTo; k++) {
			var s = slotAt(k);
			if (!s) continue;
			var w2 = s.lm.w / 2;
			if (x < s.cx - w2 || x > s.cx + w2) continue;
			var t = (x - (s.cx - w2)) / s.lm.w;
			var h = Math.round(shapeValue(s.lm.h, t) * s.lm.peak);
			if (h > best) best = h;
		}
		return best;
	}

