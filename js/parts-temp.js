	function dome(w, h, ch) {
		var rows = [];
		for (var y = 0; y < h; y++) {
			var t = (y + 1) / h;
			var half = Math.round(Math.sqrt(t) * (w / 2));
			var pad = Math.floor(w / 2) - half;
			var body = new Array(half * 2 + 1).join(ch);
			rows.push(new Array(pad + 1).join(".") + body +
				new Array(w - pad - body.length + 1).join("."));
		}
		return rows;
	}

	// 2つの形を横に並べる（★下ぞろえ。overlap ぶん重ねる）
	function beside(a, b, overlap) {
		var h = Math.max(a.length, b.length);
		var aw = a[0].length, bw = b[0].length;
		var w = aw + bw - overlap;
		var rows = [];
		for (var y = 0; y < h; y++) {
			var line = [];
			for (var i = 0; i < w; i++) line.push(".");
			var ay = y - (h - a.length), by = y - (h - b.length);
			if (ay >= 0) {
				for (i = 0; i < aw; i++) if (a[ay].charAt(i) !== ".") line[i] = a[ay].charAt(i);
			}
			if (by >= 0) {
				for (i = 0; i < bw; i++) {
					var x = aw - overlap + i;
					if (b[by].charAt(i) !== "." && x >= 0 && x < w) line[x] = b[by].charAt(i);
				}
			}
			rows.push(line.join(""));
		}
		return rows;
	}

