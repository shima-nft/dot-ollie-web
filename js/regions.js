	//   ★この世界での「いちばん奥が終わるまで」（★種で 300〜500m のどこかに決まる）
	var _far = 0, _farSeed = null;
	function farShift() {
		var sd = WD.getSeed();
		if (sd !== _farSeed) { _farSeed = sd; _far = 0; }
		if (_far) return _far;
		return (_far = Math.round((END_MIN_M +
			WD.rand(9901, sd + 3571) * (END_MAX_M - END_MIN_M)) * M_DOTS));
	}

	// ★いちばん奥の背景レイヤーの速さ（★帯も部品の層も、まとめて見る）
	var _back = 0;
	function backSpeed() {
		if (_back) return _back;
		var lo = 0;
		var L = global.DotParts && global.DotParts.LAYERS;
		if (L) for (var i = 0; i < L.length; i++) {
			if (L[i].on && L[i].speed > 0 && (!lo || L[i].speed < lo)) lo = L[i].speed;
		}
		var B = global.DotSkyline && global.DotSkyline.BANDS;
		if (B) for (var j = 0; j < B.length; j++) {
			if (B[j].speed > 0 && (!lo || B[j].speed < lo)) lo = B[j].speed;
		}
		return (_back = lo || 0.03);
	}

	// ★背景レイヤーの速さを、手前から奥の順に全部集める（★帯も部品の層も）
	var _sps = null;
	function allSpeeds() {
		if (_sps) return _sps;
		var out = [], seen = {};
		function add(sp) {
			if (!(sp > 0) || sp >= 1) return;      // ★1 以上 ＝ 地面と一緒に流れるもの
			var k = Math.round(sp * 1000);
			if (!seen[k]) { seen[k] = 1; out.push(sp); }
		}
		var L = global.DotParts && global.DotParts.LAYERS;
		if (L) for (var i = 0; i < L.length; i++) if (L[i].on) add(L[i].speed);
		var B = global.DotSkyline && global.DotSkyline.BANDS;
		if (B) for (var j = 0; j < B.length; j++) add(B[j].speed);
		out.sort(function (a, b) { return b - a; });   // ★手前 → 奥
		return (_sps = out);
	}

	// ★この世界の「ひらけ具合」（★1 = ふつう。★それ以外 ＝ ばらける世界）
	var _wild = 0, _wildSeed = null;
	function wildP() {
		var sd = WD.getSeed();
		if (sd !== _wildSeed) { _wildSeed = sd; _wild = 0; }
		if (_wild) return _wild;
		return (_wild = (WD.rand(7717, sd + 8123) >= WILD_RATE) ? 1 : 2);
	}

	// ------------------------------------------------------------
	// ■ ★★★★レイヤーごとの「終わりのずれ」の表（★1回だけ作って覚える）
	// ------------------------------------------------------------
	var _tbl = null, _tblSeed = null;
	function shiftTable() {
		var sd = WD.getSeed();
		if (sd !== _tblSeed) { _tblSeed = sd; _tbl = null; }
		if (_tbl) return _tbl;
		var sps = allSpeeds(), far = farShift();
		var f = 1 / frontSpeed(), deepest = 1 / backSpeed() - f;
		var v = [], i;
		for (i = 0; i < sps.length; i++) {
			v.push(deepest > 0 ? far * (1 / sps[i] - f) / deepest : 0);
		}
		if (wildP() !== 1) {
			// ★★レイヤーごとに別のサイコロ
			for (i = 0; i < v.length; i++) {
				v[i] *= WILD_LO + WD.rand(i * 13 + 7719, sd + 8123) * (WILD_HI - WILD_LO);
			}
			// ★★★**並べ替えて、手前から順に配り直す** ＝ 順番は絶対に入れ替わらない
			v.sort(function (a, b) { return a - b; });
			// ★★決めた 300〜500m を**はみ出したときだけ**、全部を縮めます。
			//   ★いつも合わせ直すと、★★**全体が縮んで「遠山が長い世界」が作れません**
			//     （★実際そうなった: 丘20m/遠山72m と、両方短くなっていた）
			var mx = v[v.length - 1];
			if (mx > far) for (i = 0; i < v.length; i++) v[i] = v[i] * far / mx;
		}
		_tbl = {};
		for (i = 0; i < sps.length; i++) _tbl[Math.round(sps[i] * 1000)] = Math.round(v[i]);
		return _tbl;
	}

	function endShift(speed) {
		if (!END_ON || !speed || speed >= frontSpeed()) return 0;
		var t = shiftTable()[Math.round(speed * 1000)];
		if (t !== undefined) return t;
		// ★表に無い速さ（★ランドマークなど）は、比でそのまま出す
		var f = 1 / frontSpeed(), deepest = 1 / backSpeed() - f;
		return (deepest > 0) ? Math.round(farShift() * (1 / speed - f) / deepest) : 0;
	}

	// ------------------------------------------------------------
	// ■ ★★★★「陸は、奥のレイヤーほど両側に広い」（2026-08-27）
	// ------------------------------------------------------------
	//
	//   ★★★はじめは「終わりを遅らせる」だけにしていました。
	//     ★それだと**海から陸へ戻るとき**、★★**手前の丘が先に立ち上がって**
	//       ★★★背後に遠山がいないまま空に接し、**溶けました**（★実測 14.3%）。
	//
	//   → ★**両側に広げる**（★前後 `endShift` の範囲を見て、いちばん大きい値を採る）。
	//     ★★これで:
	//         ・陸 → 海 …… ★**手前から順に終わる**
	//         ・海 → 陸 …… ★**奥から順に現れる**
	//     ★★★どちらも「遠くのものほど、広い範囲に存在する」＝ **見た目として自然**。
	//   ★なめらかさは壊れません（★区分ごとにまっすぐな線の最大値なので、崖ができない）
	function widen(fn, x, speed) {
		var sh = endShift(speed);
		if (!sh) return fn(x);
		var v = fn(x), a = fn(x - sh), b = fn(x + sh);
		return Math.max(v, Math.max(a, b));
	}

	function bandScale1(name, xx, d, speed) {
		var r = at(xx, fadeOf(speed));
		var ma = hOf(mulOf(r.a, "bands", name, undefined, d), d);
		var mb = hOf(mulOf(r.b, "bands", name, undefined, d), d);
		return (r.a === r.b) ? ma : lerp(ma, mb, r.t);
	}

	// ★その列で「B側」を出すか（t = B の混ざり具合 0〜1 / x = 列 / o = ずらす量）
	function pickB(t, x, o) {
		if (t <= 0) return false;
		if (t >= 1) return true;
		// ★★★「きっぱり」…… 混ぜないで、半分を越えたら向こう側にする
		if (MIX_STYLE !== "dither") return t >= 0.5;
		var i = (((x + (o || 0)) % 8) + 8) % 8;
		return t > (BAYER8[i] + 0.5) / 8;
	}

	// ★出やすさで地域を1つ選ぶ（★枠の番号 k と種だけで決まる）
	//   ★★1コマに何百回も聞かれるので、**枠ごとに覚えておきます**
	//     （★種が変わったら捨てる ＝ 世界が変われば必ず引き直す）
	var tCache = {}, tSeed = null, tune = 0;
	function typeAt(k) {
		if (!REGION_ON || REGIONS.length === 0) return REGIONS[0];
		var sd = WD.getSeed();
		if (sd !== tSeed) { tSeed = sd; tCache = {}; }
		if (tCache[k] !== undefined) return tCache[k];
		return (tCache[k] = typeRun(k));
	}

	// ★★★★`minRun` …… その地域が「最低いくつの枠ぶん続くか」（2026-08-27）
	//   ★手前の枠をさかのぼって、★★**まだ続いている地域があればそれを採ります**。
	//   ★★★さかのぼる数は決まっている（いちばん長い `minRun` まで）ので、
	//     ★**その場で計算できる**性質は崩れません（＝ 無限・戻れば同じ・軽い）
	var _maxRun = 0;
	function maxRun() {
		if (_maxRun) return _maxRun;
		for (var i = 0; i < REGIONS.length; i++) {
			if ((REGIONS[i].minRun || 1) > _maxRun) _maxRun = (REGIONS[i].minRun || 1);
		}
		return _maxRun;
	}
	function typeRun(k) {
		// ★★**遠い枠から先に**調べます（★近い枠から見ると、自分自身で必ず決まってしまう）
		for (var b = maxRun() - 1; b >= 1; b--) {
			var t = typeRaw(k - b);
			if ((t.minRun || 1) > b) return t;      // ★その地域は、まだここまで続いている
		}
		return typeRaw(k);
	}

	function typeRaw(k) {
		var total = 0, i;
		for (i = 0; i < REGIONS.length; i++) total += (REGIONS[i].weight || 1);
		var r = WD.rand(k, WD.getSeed() + 9137) * total;
		for (i = 0; i < REGIONS.length; i++) {
			r -= (REGIONS[i].weight || 1);
			if (r <= 0) return REGIONS[i];
		}
		return REGIONS[REGIONS.length - 1];
	}

	// ------------------------------------------------------------
	// ■ ★★★その場所は、どの地域か（★この作品でいちばん大事な関数）
	// ------------------------------------------------------------
	//   返すもの: { a: 手前の地域, b: 先の地域, t: b の混ざり具合(0〜1) }
	//   ★★境目の前後 REGION_FADE の中だけ、a と b が違います。
	//     ★それ以外は a === b（★混ぜようがない ＝ 何も起きない）
	//   ★★★`force()` で1つに固定できます（★調整ページとテストが使う）。
	//     ★`js/scenery.js` の `FORCE_TIME` / `FORCE_WEATHER` と同じ考え方。
	//     ★★**渡す前に必ず null に戻すこと**（★固定したまま遊ぶと地域が変わらない）
	var forced = null;
	// ★★そのレイヤーの「終わりにかける幅」（ドット）。★画面の列数から逆算する
	function fadeOf(speed) {
		if (!speed) return REGION_FADE;
		var lim = REGION_LEN * 0.45;             // ★枠からはみ出さないように
		return Math.min(Math.round(FADE_COLS / speed), lim);
	}

	function at(x, fade) {
		if (forced) return { a: forced, b: forced, t: 1 };
		if (!REGION_ON) { var only = REGIONS[0]; return { a: only, b: only, t: 1 }; }
		var REGION_FADE = (fade === undefined || fade === null) ? fadeOf(0) : fade;
		var k = Math.floor(x / REGION_LEN);
		var d = x - k * REGION_LEN;              // ★この枠に入ってから何ドットか
		var half = REGION_FADE / 2;
		//   ★★となり合う枠が**同じ地域**なら、混ぜようがないので `t: 1` に揃えます
		//     （★揃えないと、境目で数字だけが飛んで見えます）
		if (REGION_FADE > 0 && d < half) {
			// ★手前の枠との境目（★境目のまん中で half & half）
			var pa = typeAt(k - 1), pb = typeAt(k);
			return { a: pa, b: pb, t: (pa === pb) ? 1 : (0.5 + d / REGION_FADE) };
		}
		if (REGION_FADE > 0 && d > REGION_LEN - half) {
			// ★次の枠との境目
			var na = typeAt(k), nb = typeAt(k + 1);
			return { a: na, b: nb,
				t: (na === nb) ? 1 : ((d - (REGION_LEN - half)) / REGION_FADE) };
		}
		var cur = typeAt(k);
		return { a: cur, b: cur, t: 1 };
	}

	// ★2つの数を混ぜる
	function lerp(a, b, t) { return a + (b - a) * t; }

	// ★その1点で、ランドマークを置いてよいか（★境目では「置かない」を優先）
	function lmOne(x) {
		var r = at(x);
		var a = (r.a.landmark === undefined) ? 1 : r.a.landmark;
		var b = (r.b.landmark === undefined) ? 1 : r.b.landmark;
		return Math.min(a, b);
	}

	// ★★色の置き換え表を「色の番号 → 色の番号」に直しておく（★1回だけ）
	//   ★島さんは**文字**で書きます（読みやすいので）。★描くときは番号のほうが速い
	function idxMapOf(R) {
		if (!R || !R.ground) return null;
		if (R._gidx) return R._gidx;
		var PAL = global.DotPalette, m = {};
		for (var ch in R.ground) {
			if (!Object.prototype.hasOwnProperty.call(R.ground, ch)) continue;
			var from = PAL.indexOfChar(ch), to = PAL.indexOfChar(R.ground[ch]);
			if (from >= 0 && to >= 0) m[from] = to;
		}
		R._gidx = m;
		return m;
	}

	// ★★帯の書き方は2つ …… 数字だけ（高さの倍率）／ `{ h: 高さ, color: 色 }`
	function hOf(v, d) {
		if (v === null || v === undefined) return d;
		if (typeof v === "object") return (v.h === undefined) ? d : v.h;
		return v;
	}
	// ★その地域の「倍率」を引く（★書いていなければ既定値）
	function mulOf(R, table, key1, key2, dflt) {
		var m = R && R[table];
		if (!m) return dflt;
		if (key1 !== undefined && m[key1] !== undefined) return m[key1];
		if (key2 !== undefined && m[key2] !== undefined) return m[key2];
		return dflt;
	}

