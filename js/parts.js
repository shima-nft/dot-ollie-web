//   島さん（2026-08-11）:
//   > 縦の4層ではなく「距離の異なる物体を、複数の独立したレイヤーとして配置する」です。
//   >   遠い建物 → 小さい / 近い植物 → 大きい
//
//   ★**画面を縦に分けているのではありません。** 「距離のちがう空間」を並べています。
//
// ■ ★★層の数は決めうちではありません（島さんの指定）
//
//   いまは4つですが、**これは暫定です。**
//   遊んでみて奥行きが足りなければ、**下の表に1行足すだけ**で「中遠景」「近景」が増えます。
//   ★「4層で正しい」という前提にはしないこと。
//
// ■ ★島さんが背景を触るのは、このファイルだけ
//
//     ① 層の表    …… どの距離に、どれくらいの速さで流れる空間を置くか
//     ② 部品の表  …… その空間に何を、どれくらいの間隔で置くか
//
//   色の淡さ（空気遠近）は **`js/tint.js`**。絵そのものは `assets/parts/` の PNG。
//
// ■ ★部品を1つ増やす手順（4か所）
//
//     ① PNG を `assets/parts/` に置く（1コマだけの絵でよい）
//     ② `tools/sheet2art.py` の `SHEETS` に1行（→ `js/parts-art.js` ができる）
//     ③ 下の `PARTS` に1行
//     ④ `index.html` と `sw.js` に読み込みを1行（★初回だけ。2つ目からは不要）
//
//   → 「絵を反映する.bat」→「テストする.bat」
// ============================================================
(function (global) {
	"use strict";

	// ============================================================
	// ■■■ ① 層の表 —— ★奥から手前の順に並べること ■■■
	// ============================================================
	//
	//   name    … 層の名前（下の部品の表から、この名前で呼ぶ）
	//   speed   … 流れる速さ。★**地面を 1 とする。小さいほど遠くに見える**
	//   filter  … `js/tint.js` のどのフィルターをかけるか（null = かけない）
	//   front   … 0 = 地面より**奥**に描く / 1 = 地面より**手前**に描く
	//   clear   … 1 = ★**地面のすぐ上を空けておく**（主役と地面を背景に埋もれさせないため）
	//   bake    … 1 = 焼き付けて速くする / 0 = 毎コマ描く（★見た目は同じ）
	//   on      … 0 にすると、その層をまるごと消せる
	//   horizon … ★**その層をまるごと持ち上げる量**（ドット）。★使わなくてよい（既定 0）
	//   standing… 1 = 地平に立つ / 0 = 何かに付いている・浮かぶ（下の決まりBから外れる）
	//   sinkInFront … ★1 = **地面より下がったものは、プレイヤーより手前に描く**（前景用）
	//
	//   ★★speed は「奥ほど小さい」順に並べること。テストが見張っています
	//
	// ■■ ★★足元の高さの決まり（2026-08-11 島さんの指摘で決めた）■■
	//
	//   島さん「山より基準値が高い木があり、これは浮いてるように見えてしまった」
	//   島さん「**基準値が同じで美しいのもある**ため考え直して」
	//
	//   → **「奥ほど足元が高い」は決まりにしません。** 同じ地平線に揃った絵は美しいので。
	//     ★困るのは1つだけ:
	//
	//       ★★**手前のものが、奥のものより上に来ないこと。同じ高さは OK。**
	//
	//   **持ち上げ量 = `horizon`（層） + `lift`（部品・ばらつく）** として、
	//
	//     A: 持ち上げ量は **0 以上**（0 を下回ると「空けておく帯」を食う）
	//     B: ★**奥の層の最小 ≧ 手前の層の最大**（★**同じは OK**）
	//
	//   ★どちらも `test/parts.test.js` 【10】が数字で止めます。
	//   ★**全部 0 のままでもかまいません**（＝ぜんぶ同じ地平線に並ぶ。それも許される形）
	var LAYERS = [
		{ name: "最遠景", speed: 0.05, filter: "far3", front: 0, clear: 1, bake: 1, on: 1,
			horizon: 10, standing: 1 },
		{ name: "遠景",   speed: 0.15, filter: "far2", front: 0, clear: 1, bake: 1, on: 1,
			horizon: 5,  standing: 1 },
		// ★★「光もの」…… フィルターを**通さない**層。
		//   夜になっても、窓・月・花の芯・水の反射だけは明るいまま残したいときはここへ。
		//   （フィルターは層まるごとにかかるので、同じ距離の中の「窓」と「壁」は分けられない。
		//     分けたいものを、この層に出す）
		//   ★速さと持ち上げ量は**遠景と同じ**（窓は遠景のビルに付いているため）。
		//     ★`standing: 0` ＝ 地平に立っていないので、決まりB から外す
		{ name: "光もの", speed: 0.15, filter: null,   front: 0, clear: 1, bake: 1, on: 1,
			horizon: 5,  standing: 0 },
		{ name: "中景",   speed: 0.40, filter: "far1", front: 0, clear: 1, bake: 1, on: 1,
			horizon: 2,  standing: 1 },
		// ★前景 …… 地面と同じ速さ。フィルターなし ＝ いちばん濃く鮮やか
		//   ★`sinkInFront: 1` … **地面より下がった草花は、プレイヤーより手前に描く**
		//     （島さん「地面に埋もれているのではなく、手前にあるという表現に見せたい」）
		//     ★0 にすると、前の形（ぜんぶプレイヤーの後ろ）に戻ります
		{ name: "前景",   speed: 1.00, filter: null,   front: 1, clear: 0, bake: 1, on: 1,
			standing: 1, sinkInFront: 1 }
		// ★足すならここ。例:
		// { name: "中遠景", speed: 0.25, filter: "far2", front: 0, clear: 1, bake: 1, on: 1,
		//   horizon: 3, standing: 1 },
	];

	// ★地面のすぐ上、何行を空けておくか（上の `clear: 1` の層に効く）
	//   ★ここを 0 にすると、背景が道のきわまで降りてきて
	//     **スケーターとコーンが読みにくくなります**
	//     （出典: 判定のあるものを強調する —— 地形が演出に負けるとアクションとして致命的）
	var CLEAR_ROWS = 10;

	// ============================================================
	// ■■■ ② 部品の表 —— ★1部品＝1行 ■■■
	// ============================================================
	//
	//   name   … 名前（テストのメッセージに出るだけ）
	//   layer  … ★上の層の表にある名前。★打ち間違いはテストが止めます
	//   art    … 絵の名前（`js/parts-art.js` の中の名前 / 仮の絵なら `js/parts-temp.js`）
	//   weight … 出やすさ。★同じ層の中での取り合い（大きいほどよく出る）
	//   gap    … 次の部品までの間隔 [ここから, ここまで]（★その層での距離）
	//   at     … 足元をどこに置くか
	//              "地平" … 遠くの地平線に立つ（★背景の層はふつうこれ）
	//              "地面" … ★**いまの地面の起伏に乗る**（speed 1.00 の層だけ）
	//              "空"   … 浮かぶ（`y` で高さを指定）
	//   y      … `at:"空"` のときの、絵の上端の行
	//   lift   … ★★**基準からどれだけ持ち上げるか**（プラスが上・ドット）
	//              数字1つ  … いつもその高さ（例: `lift: 8`）
	//              [下, 上] … ★**その間でばらつく**（例: `lift: [-2, 4]`）
	//
	//   ★★`lift` を範囲にする理由（島さん 2026-08-11）:
	//     > 木が一定の高さにあるのと、一マス下にあったりするのとでは
	//     >   どちらが自然に見えますか
	//     **一直線に並ぶと「置いた」ように見え、ばらつくと「生えている」ように見えます。**
	//
	//   ★★このばらつきは **種（シード）で決めていません**（島さんの指定）。
	//     決める材料は **「その場所」** です ＝ **その場所に立っているものは、いつもその高さ**。
	//     ・種を入れないので「今日の世界」には縛られない
	//     ・でも**描き直しても動かない**（時間帯を変えた瞬間に木が飛び跳ねない）
	//     ・走るたびに**置かれる場所そのもの**が変わるので、結果として毎回ちがう並びになる
	//
	//   ★★大きさは変えません。**島さんが描いたまま置きます。**
	//     （遠い建物を小さく描くのは島さんの持ち場。
	//       2026-07-31 に AI が絵を勝手に作り替えた事故があるので、**サイズも勝手に変えない**）
	var PARTS = [
		// ★★いまは全部「仮の絵」です（四角と線）。
		//   **本物の絵が1つでも入ったら、この節ごと消せます**（`js/parts-temp.js` も一緒に）
		//   ★`lift` は「その層の持ち上げ量（horizon）からの、さらなるばらつき」。
		//     マイナスも書けます（horizon が吸収します）
		{ name: "仮・遠い山",   layer: "最遠景", art: "TEMP_MOUNTAIN", weight: 1, gap: [180, 340], at: "地平", lift: [-3, 3] },
		{ name: "仮・遠いビル", layer: "遠景",   art: "TEMP_TOWER",    weight: 2, gap: [120, 260], at: "地平", lift: [-2, 2] },
		{ name: "仮・丘",       layer: "遠景",   art: "TEMP_HILL",     weight: 1, gap: [140, 280], at: "地平", lift: [-2, 1] },
		{ name: "仮・木",       layer: "中景",   art: "TEMP_TREE",     weight: 3, gap: [70, 160],  at: "地平", lift: [-2, 1] },
		{ name: "仮・小屋",     layer: "中景",   art: "TEMP_HUT",      weight: 1, gap: [90, 200],  at: "地平", lift: [-2, 0] },
		{ name: "仮・窓あかり", layer: "光もの", art: "TEMP_WINDOW",   weight: 1, gap: [90, 200],  at: "地平", lift: [0, 16] },
		// ★★2026-08-11 島さん「地面に置かれる草花に、地面から0〜5マス下までのランダム性を」
		//   ★lift はプラスが上なので、**0〜5マス下 ＝ [-5, 0]**。
		//     前景は地面より**手前**に描くので、下がった分は地面に埋まって見える
		{ name: "仮・草",       layer: "前景",   art: "TEMP_GRASS",    weight: 4, gap: [18, 46],   at: "地面", lift: [-5, 0] },
		{ name: "仮・花",       layer: "前景",   art: "TEMP_FLOWER",   weight: 1, gap: [60, 150],  at: "地面", lift: [-5, 0] }
	];

	// ============================================================
	// 外に出す窓口
	// ============================================================
	global.DotParts = {
		LAYERS: LAYERS,
		PARTS: PARTS,
		CLEAR_ROWS: CLEAR_ROWS,

		layerIndex: function (name) {
			for (var i = 0; i < LAYERS.length; i++) if (LAYERS[i].name === name) return i;
			return -1;
		},
		// その層に置く部品だけを取り出す
		partsOf: function (name) {
			return PARTS.filter(function (p) { return p.layer === name; });
		},
		// ★仮の絵がまだ混ざっているか（本物が入ったら片付ける目印）
		hasTemp: function () {
			return PARTS.some(function (p) { return String(p.art).indexOf("TEMP_") === 0; });
		}
	};
})(typeof window !== "undefined" ? window : globalThis);
