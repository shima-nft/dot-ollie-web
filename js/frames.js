	// 表の合計(ミリ秒) = その技1回にかかる時間
	function totalMs(ms) {
		var t = 0;
		for (var i = 0; i < ms.length; i++) t += ms[i];
		return t;
	}

	// 跳びはじめてから n ミリ秒たったとき、何コマ目か。
	// 最後まで行ったら -1(＝技が終わった)を返す
	function frameAt(ms, n) {
		var acc = 0;
		for (var i = 0; i < ms.length; i++) {
			acc += ms[i];
			if (n < acc) return i;
		}
		return -1;
	}

