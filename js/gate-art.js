//
//   ■ ★差し替えるときの手順（コーン・岩とまったく同じ）
//     ① `assets/sprites/gate-export.png` に描く（64×64のマス）
//     ② `tools/sheet2art.py` の `SHEETS` に1行足す
//     ③ 「絵を反映する.bat」→ このファイルが**自動生成に置き換わる**
//
//   ■ ★★★守ってほしい決まり（★描き替えるときも）
//
//     **① 障害物は、必ず黒（`9`）で縁取る。**
//        ★理由: 背景の部品も同じ色を使うので、縁取りが無いと
//          「ぶつかるもの」と「ただの背景」が見分けられない。
//        ★`test/sprites.test.js`【4.5】が輪郭を1ドットずつ見張っています。
//
//     **② 扉は「跳んでも越えられない」と、見ただけで分かる高さにする。**
//        ★主役がいちばん高く跳んだときの足元は **25ドット**。
//          いまの扉は **30ドット**あるので、絵として「越えられない」が伝わります。
//        ★★これは見た目の話ではなく**ルールの説明**です。
//          扉には当たり判定の例外があり、**跳んでも必ず当たります**。
//          絵が低いと「跳べば越えられそうなのに当たった」＝理不尽になります。
//
//     **③ 扉には「鍵穴」を描く。**
//        ★★★**画面に文字で説明を出しません**（島さん「プレイヤー自身が気付くことが重要」）。
//          ★鍵穴だけが「これは鍵で開くものだ」と伝える唯一の手がかりです。
//
//   ■ 中身（`js/cone-art.js` と同じ形）
//     FRAMES   … 1コマ = { x, y, rows }。rows の1文字 = `js/palette.js` の色の番号
//     FEET_ROW … 絵の中で「足がつく」いちばん下の行。ここが道の面に重なる
//                ★決め方: `FEET_ROW = y + rows.length - 1`
//
//   ★色そのものは `js/palette.js` にある（ここには持たない）
//     9 = まっ黒（★縁取り） / 7 = 銀（石枠） / d = 茶（扉板）
//     a = 濃紺（★開いた先の暗がり） / j = 黄（鍵）
// ============================================================
