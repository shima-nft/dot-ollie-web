		"979ddddddd979",
		"979ddddddd979",
		"979dd999dd979",   // ★鍵穴（上）
		"979dd999dd979",
		"979ddd9ddd979",   // ★鍵穴（下・細い）
		"979ddd9ddd979",
		"979ddddddd979",
