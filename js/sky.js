// ============================================================
// ★★ 空 —— 島さんの持ち場 ★★
// ============================================================
//
//   島さん（2026-08-20）:
//   > 1. 空（Sky / Farthest Background）
//   >   ・薄い青〜やや明るい青のグラデーション。
//   >   ・雲は後で別レイヤーとして追加されるので、この段階ではほぼ単色の空。
//   >   ・最も遠くに感じさせるため、彩度を抑えめに。
//
//   ★★2026-08-20 まで、空は**一色**（藍）でした。ここが**8レイヤーの1枚目**になります。
//
// ■ ★★25色でグラデーションをどう作るか
//
//   ★**中間色を作れません**（`js/palette.js` の25色しか使えない）。
//   → **横に長い帯を上から順に置く**（＝ドット絵のグラデーションのやり方）。
//     ★段の境目がはっきり出ますが、**それがドット絵の空**です。
//
// ■ ★★★なぜ「上が明るく、下が濃い」のか（★2026-08-20 に**逆にした**）
//
//   ★はじめは実際の空どおり「天頂が濃く、地平線ほど淡い」で作りました。
//   ★★ところが島さんが**雪山の絵**（銀 #afb3b5 ＋ 生成り）を描いたとき、
//     ★★★**銀の面が明るい空（空色 #3ebde0）に溶けました**（★実測: 6000ドット中138ドット）。
//     ★銀と空色は**明るさがほぼ同じ**（0.43 と 0.42）。
//
//   → ★★**山が立つ「下側」を濃くした。** これで:
//     ・★島さんの雪山（銀・白）が、藍の空を背にして**くっきり立つ**
//     ・★遠山（藤色）も藍の前で見える（比 2.6）
//     ・★雲（生成り）は明るい上側にいるので、そのまま白く見える
//     ・★★**スケーターの服（水色）は、水色の帯（行37〜57）に絶対届かない**
//
//   ★★★**絵は1ドットも触っていません**（絵は島さんの持ち場）。動かしたのは空の色だけ。
//   ★★そして**下の明るい帯は、ほとんど山に隠れます**（山並みは画面の58行目まで来る）。
//     ★つまり明るい帯は「山の向こうに見える、霞んだ空」として働きます。
//
// ■ ★★★水色（21）を主役の高さに置かないこと
//
//   ★★**スケーターの服が水色（21）**です。空の同じ色と重なると主役が溶けます。
//   ★2026-08-13 に空を「青 → 藍」に変えたのは、まさにこの理由でした。
//   → ★水色の帯は**画面の上のほう**にだけ置きます（主役が跳んでも届かない高さ）。
//   ★`test/screen.test.js` が「主役と背景の明るさの比」を見張っています。
//
// ■ 書き方
//
//     { color: "色の文字", h: 高さの割合 }   ★上から順に。h の合計は 1.0
//
//   ★色の文字は `js/palette.js` の文字（0〜9, a〜o）。
//   ★1行にすれば**一色の空**に戻ります（＝ 2026-08-20 より前の見た目）。
// ============================================================
(function (global) {
	"use strict";

	var PAL = global.DotPalette;

	// ============================================================
	// ■■■ ★空の帯 —— 触るのはここだけ ■■■
	// ============================================================
	//   ★★★h は「画面の高さ」に対する割合ではなく、**空として使える高さ**
	//     （＝画面のいちばん上から地面の基準線まで）に対する割合です。
	//     ★だから地面の位置を変えても、空の割り振りは崩れません
	var SKY = {
		// ★★★2026-08-21、島さんが `tools/preview-colors.html` で選んだ色
		//   ★上が濃い水色 → 下が明るい空色（★実際の空と同じ「上が濃い」向き）。
		//   ★★中と下が**同じ空色**なので、そこの境界は見えません（★島さんの選択）。
		//   ★★★主役（水色の服）が届くのは行75あたり ＝ **空色の帯**。水色の帯は行0〜37なので接しません
		DAY: [
			{ color: "l", h: 0.30 },   // ★天頂 …… 水色 #29adff（★いちばん濃い）
			{ color: "8", h: 0.16 },   // ★中空 …… 空色 #3ebde0
			{ color: "8", h: 0.54 }    // ★地平 …… 空色 #3ebde0（★★中空と同じ ＝ 境界が見えない）
		],
		// ★★夕方・夜は `js/tint.js` と同じで、**まだ切り替えを入れていません**。
		//   ★ここに書いておけば、時間帯を入れるときにそのまま使えます
		EVENING: [
			{ color: "b", h: 0.42 },   // 暗い紫
			{ color: "h", h: 0.26 },   // 赤
			{ color: "i", h: 0.32 }    // 橙
		],
		NIGHT: [
			{ color: "9", h: 0.50 },   // まっ黒
			{ color: "a", h: 0.30 },   // 濃紺
			{ color: "0", h: 0.20 }    // 藍
		]
	};

	// ★いま使う時間帯。★`js/tint.js` の `FIXED_TIME` と合わせること
	var FIXED_TIME = "DAY";

	// ============================================================
	// ■■■ ★★★色の変わり目のドットの並び —— ★島さんの持ち場 ■■■
	// ============================================================
	//
	//   > 島さん「そらの色の変わる境界線は幅3ドット分グラデーション入れてください。
	//   >         同じ色で(奥から)」（2026-08-20）
	//   > ★★島さんが `tools/preview-dither.html` で**自分で描いて決めた並び**（2026-08-20）
	//
	//   ★★25色では中間の色が作れません。新しい色も足しません（島さんの「同じ色で」）。
	//   → ★★★**ドットを置いて混ぜます。**
	//
	//   ■ ★★書き方 —— **見たままの形で書く**
	//
	//     ・**上の行から順に**「境界から遠い → 近い」
	//     ・`#` ＝ **手前（下）の色を置く** / `.` ＝ 何もしない（奥の色のまま）
	//     ・1行の長さが「横にくり返す1組」（★4でも8でも16でもよい）
	//
	//   ★★★**この表を書き換えるだけで、並びが変わります。**
	//     ★描いて決めるページ: `tools/preview-dither.html`
	//       （★マスを押して描くと、この形の文字列が出てきます）
	//
	//   ■ ★いまの並び（島さんが決めたもの）
	//     ★境界の2ドット上に、**手前の色の線が1本**走ります。
	//     ★★ぼかすのではなく、**線を1本足す**形（★ドット絵らしい、きっぱりした見え方）
	var DITHER_ROWS = [
		"....",   // ★境界の 4 ドット上
		"....",   // ★境界の 3 ドット上
		"####",   // ★境界の 2 ドット上 …… ★ここに線が1本
		"...."    // ★境界の 1 ドット上
	];

	// ★グラデーションの幅（＝上の表の行数）。★表を増減すれば自動で変わります
	//   ★★`DITHER_ROWS` を空（`[]`）にすると、**くっきりした境界**に戻ります
	var DITHER = DITHER_ROWS.length;

	// ★★その行のその列に、手前の色を置くか（★x = 列 / k = 上から何行目か）
	function ditherOn(x, k) {
		var row = DITHER_ROWS[k];
		if (!row || !row.length) return false;
		return row.charAt(((x % row.length) + row.length) % row.length) === "#";
	}

	// ============================================================
	// ここから下は仕組み（ふつうは開かなくてよい）
	// ============================================================

	// ★★帯を「画面の行」に直す。★合計が空の高さぴったりになるよう、最後の帯で辻褄を合わせる
	//   （割合を足しても丸めで1〜2ドット余ることがある。★空いた行は空色のままにしない）
	function rowsOf(skyBottom, time) {
		var list = SKY[time || FIXED_TIME] || SKY.DAY;
		var out = [], y = 0;
		for (var i = 0; i < list.length; i++) {
			var last = (i === list.length - 1);
			var h = last ? (skyBottom - y) : Math.round(skyBottom * list[i].h);
			if (h < 0) h = 0;
			out.push({ color: list[i].color, index: PAL.indexOfChar(list[i].color), y: y, h: h });
			y += h;
		}
		return out;
	}

	global.DotSky = {
		SKY: SKY,
		FIXED_TIME: FIXED_TIME,
		DITHER: DITHER,
		DITHER_ROWS: DITHER_ROWS,
		ditherOn: ditherOn,
		time: function () { return FIXED_TIME; },
		rowsOf: rowsOf,
		// ★その時間帯の帯の数（テストが使う）
		count: function (time) { return (SKY[time || FIXED_TIME] || SKY.DAY).length; }
	};
})(typeof window !== "undefined" ? window : globalThis);
