// ============================================================
// ★★ この世界の色（26色）—— 島さんの持ち場 ★★
// ============================================================
//
// **絵も空も街も道も、ここに並んでいる色しか使えません。**
// 番号がそのまま、絵を描くときの文字になります。
//
//     0〜9 → "0"〜"9"      10〜15 → "a"〜"f"      16〜25 → "g"〜"p"
//
// ■ 二段構えになっています
//     **0〜15** … ★島さんがスケーターを描いたときの16色。**番号を動かさないこと**
//                （`js/ollie-art.js` の絵がこの番号で書かれているため）
//     **16〜25** … ★PICO-8 の色のうち、上の16色に入っていなかったもの（2026-08-09 に追加）
//
// ■ 色を足したいとき
//   **いちばん下に足してください。** 途中に割り込ませると、既に描いた絵の色が全部ずれます。
//   足したら `絵を反映する.bat` → `テストする.bat`。
//
// ■ ★並び順は「明るさ」と関係ありません
//   空の描き方や「auto」の色選びは、**コードが毎回明るさを測って**並べ直しています
//   （`js/scenery-draw.js` の `TONE`）。だから**好きな順で足してかまいません。**
//   2026-08-09 まではここが「暗い順」である前提でしたが、PICO-8 の並びは
//   明るさ順ではないので、**測って並べる**形に作り替えました。
// ============================================================
(function (global) {
	"use strict";

	var COLORS = [
		// ---- 0〜15: ★島さんがスケーターを描いた16色（番号を動かさない）----
		"#000000",   // 0  まっ黒                （PICO-8 black）
		"#01020b",   // 1  ほぼ黒（青より）
		"#0a0404",   // 2  ほぼ黒（赤より）
		"#000a22",   // 3  ほぼ黒（濃紺）★夜の乗算に使っている
		"#0a0e0f",   // 4  ほぼ黒
		"#10100f",   // 5  ほぼ黒（明るめ）
		"#1b1b1a",   // 6  暗い灰
		"#1d2b53",   // 7  濃紺                  （PICO-8 dark-blue）
		"#065ab5",   // 8  青
		"#83769c",   // 9  藤色                  （PICO-8 lavender）★道の色
		"#ff9081",   // 10 サーモン
		"#ffa300",   // 11 橙                    （PICO-8 orange）
		"#ffccaa",   // 12 肌色                  （PICO-8 peach）
		"#fff1e8",   // 13 生成り                （PICO-8 white）
		"#f4f6fa",   // 14 ほぼ白
		"#ffffff",   // 15 まっ白

		// ---- 16〜25: ★PICO-8 の残りの色（2026-08-09 島さんの指定で追加）----
		"#7e2553",   // g(16) 暗い紫    dark-purple
		"#008751",   // h(17) 暗い緑    dark-green
		"#ab5236",   // i(18) 茶        brown
		"#5f574f",   // j(19) 暗い灰    dark-grey
		"#c2c3c7",   // k(20) 明るい灰  light-grey
		"#ff004d",   // l(21) 赤        red
		"#ffec27",   // m(22) 黄        yellow
		"#00e436",   // n(23) 緑        green
		"#29adff",   // o(24) 水色      blue
		"#ff77a8"    // p(25) 桃        pink
	];

	// 絵の中で1色を表す文字。**番号のならびと1対1**
	var CHARS = "0123456789abcdefghijklmnop";

	global.DotPalette = {
		COLORS: COLORS,
		CHARS: CHARS,
		// 文字 → 番号（"." と "#" はここへ来ない）
		indexOfChar: function (ch) { return CHARS.indexOf(ch); },
		// 番号 → 文字
		charOfIndex: function (i) { return CHARS.charAt(i); }
	};
})(typeof window !== "undefined" ? window : globalThis);
