// ============================================================
// ★★ 世界のかたち —— 種（シード）から「終わらない地面」を作る ★★
// ============================================================
//
//   島さん（2026-08-11）:
//   > 「バイオームはまだ先。マインクラフトも初期はなかったはず。
//   >   それでもワクワクしたんだ。無限の広さや可能性に。」
//
//   なので、まず**いちばん下の1枚だけ**を敷く。
//   帯（森・海辺…）も、木や岩を置く仕組みも、音も、時間帯も**まだ入れない**。
//
// ■ ★★このファイルのいちばん大事な性質
//
//   **地面のデータをどこにも溜めていません。**
//   「種」と「いまいる場所（x）」だけから、その場で計算して答えを出します。
//
//     ・だから **何万メートル進んでも重くならない**（覚えることが増えない）
//     ・だから **戻れば必ず同じ地形**（同じ種・同じ場所なら答えは必ず同じ）
//     ・だから **端がない**（無限に続く）
//
//   これはマインクラフトが地形を作るのと同じ考え方です。
//
// ■ どうやって「なめらかな丘」を作っているか
//
//   ① まっすぐな線の上に、**一定の間隔で杭を打つ**（例：300ドットごと）
//   ② 杭の高さを、種と場所から**その場で計算**して決める（サイコロではない。必ず同じ）
//   ③ 杭と杭のあいだを **なめらかにつなぐ**
//   ④ それを「大きなうねり」「中くらい」「小さな凹凸」の3枚**重ねる**
//
//   ★重ねるのが肝です。1枚だけだと同じ形の波が続いて、すぐ飽きます。
//
// ■ 島さんが触るのは、下の「調整値」だけ
//   ★気に入らない効果は **数字を 0 にすれば消えます**（この作品の作法どおり）
// ============================================================
(function (global) {
	"use strict";

	// ============================================================
	// ■■■ 調整値 —— 触るのはここだけ ■■■
	// ============================================================

	// ■ 足元の地面
	var AMP    = 11;    // ★起伏の大きさ（基準線から上下 何ドットまで動くか）
	//                     0 にすると **まっすぐな地面**（前の形に戻る）
	var WAVE   = 300;   // ★大きなうねり1つぶんの長さ（ドット）
	//                     70ドット/秒で進むので、300 ＝ だいたい 4.3秒に1つの丘
	var DETAIL = 0.35;  // ★小さな凹凸の強さ（0 = つるんとしたうねりだけ / 1 = ごつごつ）

	// ■ ★★まれに来る「まっすぐな道」（2026-08-11 島さんの指定）
	//
	//   > 「まれに真っ直ぐで少し長めの地面もほしいです」
	//
	//   ★丘がずっと続くと、目が休まらず、じきに「同じ」に見えてきます。
	//     たまに平らな道が来ると、そこが**息継ぎ**になって、丘のほうも活きます。
	//     （出典: 単調な坂は山登りにならない —— 壁と平地を交互に作る）
	//
	//   ★**すとんと落ちません。** 丘からなだらかに降りて、しばらく平らで、
	//     またなだらかに丘へ戻ります（`FLAT_FADE` がその「なだらか」の長さ）
	var FLAT_ON       = 1;     // 1 = まっすぐな道を出す / ★0 = 出さない（ずっと丘）
	var FLAT_EVERY    = 1200;  // ★何ドットごとに「出るかどうかの抽選」をするか
	var FLAT_CHANCE   = 0.5;   // ★その抽選で当たる割合（0.5 = 半分）。
	//                            ＝ ならすと 2400ドット（約34秒）に1回。**小さいほど「まれ」**
	var FLAT_LEN_MIN  = 220;   // ★まっすぐな道の長さ。ここから
	var FLAT_LEN_MAX  = 420;   //   ★ここまでの間でばらつく（約3〜6秒）
	var FLAT_FADE     = 150;   // ★入り口と出口の「なだらか」の長さ。
	//                            ★短くすると坂が急になります（崖の見張りが止めます）

	// ■ ★遠景の稜線（奥に見える山なみ）。**要らなければ RIDGE_ON = 0**
	var RIDGE_ON    = 0;    // 1 = 出す / 0 = 出さない
	var RIDGE_UP    = 34;   // 稜線の高さ（地面の基準線から何ドット上か）
	var RIDGE_AMP   = 14;   // 稜線の起伏の大きさ
	var RIDGE_WAVE  = 520;  // 稜線のうねり1つぶんの長さ（地面より長い = ゆったり）
	var RIDGE_SPEED = 0.3;  // ★流れる速さ（地面を 1 とする）。小さいほど遠くに見える

	// ■ 見張りのための決まり（テストが読む。ふつうは触らない）
	var MAX_SLOPE = 0.35;   // ★1ドット進むごとの高さ変化の上限。
	//                         これを超えると**崖**になり、絵が破綻して着地が読めなくなる

	// ============================================================
	// 以下は仕組み。ふつうは触らない
	// ============================================================

	var seed = 1;   // いまの種。★外から読めるようにしてある（あとで画面に出せるように）

	// ------------------------------------------------------------
	// ■ 「場所」と「種」から、必ず同じ 0〜1 の数を作る
	//   ★サイコロ（Math.random）ではありません。
	//     同じ場所・同じ種なら、何度呼んでも**必ず同じ答え**になります。
	//     これが「戻っても同じ地形」「テストで再現できる」の土台
	// ------------------------------------------------------------
	function hash(i, salt) {
		var h = (Math.imul(i | 0, 374761393) + Math.imul(salt | 0, 668265263)) | 0;
		h = Math.imul(h ^ (h >>> 13), 1274126177);
		h = h ^ (h >>> 16);
		return (h >>> 0) / 4294967296;      // 0 以上 1 未満
	}

	// ------------------------------------------------------------
	// ■ 杭を打って、あいだをなめらかにつなぐ（波1枚ぶん）
	//   ★つなぎ方に「なめらかな曲線」を使っているので、杭の所で角が立ちません
	// ------------------------------------------------------------
	function wave1(x, period, salt) {
		var g = x / period;
		var i = Math.floor(g), t = g - i;
		var a = hash(i, salt), b = hash(i + 1, salt);
		var s = t * t * (3 - 2 * t);        // なめらかにつなぐ
		return a + (b - a) * s;             // 0〜1
	}

	// ------------------------------------------------------------
	// ■ 波を3枚重ねる（大きなうねり ＋ 中 ＋ 小さな凹凸）
	//   返す値は -0.5 〜 +0.5（まん中が 0）
	// ------------------------------------------------------------
	function waves(x, period, salt) {
		var w1 = 1, w2 = 0.5 * DETAIL, w3 = 0.25 * DETAIL;
		var sum = w1 * wave1(x, period, salt) +
			w2 * wave1(x, period / 3, salt + 101) +
			w3 * wave1(x, period / 9, salt + 202);
		return sum / (w1 + w2 + w3) - 0.5;
	}

	// ------------------------------------------------------------
	// ■ ★★「いまどれくらい平らか」を 0〜1 で返す（1 = 完全にまっすぐ）
	//
	//   ★ここも**データを溜めていません。** 場所と種から、その場で計算します。
	//
	//   ① 世界を FLAT_EVERY ドットずつの区画に切る
	//   ② 区画ごとに「まっすぐな道を置くか」を抽選する（種で決まるので必ず同じ）
	//   ③ 置くなら、その区画のどこに・どれくらいの長さで置くかも種で決める
	//   ④ 入り口と出口は **なだらかにつなぐ**（すとんと落とさない）
	//
	//   ★★まっすぐな道は必ず1つの区画の中に収まるようにしてある。
	//     こうしておくと「となりの区画も見に行く」必要がなくなり、計算が1回で済む
	// ------------------------------------------------------------
	function smooth(u) { return u * u * (3 - 2 * u); }

	function flatness(x) {
		if (!FLAT_ON) return 0;
		var k = Math.floor(x / FLAT_EVERY);
		if (hash(k, seed + 4242) >= FLAT_CHANCE) return 0;      // この区画は「はずれ」
		var len = FLAT_LEN_MIN + hash(k, seed + 4343) * (FLAT_LEN_MAX - FLAT_LEN_MIN);
		var total = len + 2 * FLAT_FADE;
		var room = FLAT_EVERY - total;
		if (room < 0) return 0;                                 // 設定が詰まりすぎ（保険）
		var t = x - (k * FLAT_EVERY + hash(k, seed + 4444) * room);
		if (t <= 0 || t >= total) return 0;                     // まだ／もう外
		if (t < FLAT_FADE) return smooth(t / FLAT_FADE);        // 入り口（なだらかに）
		if (t > total - FLAT_FADE) return smooth((total - t) / FLAT_FADE);  // 出口
		return 1;                                               // ★まっすぐな道の本体
	}

	// 地面の高さ（丸める前）。★平らな区間では 0 ＝ 基準線ぴったりになる
	function heightRaw(x) {
		return waves(x, WAVE, seed) * 2 * AMP * (1 - flatness(x));
	}

	// ------------------------------------------------------------
	// ■ 外に出す窓口
	// ------------------------------------------------------------
	global.DotWorld = {
		// ★調整値（テストと ollie.js が読む。書き換えるのは上の var のほう）
		AMP: AMP, WAVE: WAVE, DETAIL: DETAIL, MAX_SLOPE: MAX_SLOPE,
		FLAT_ON: FLAT_ON, FLAT_EVERY: FLAT_EVERY, FLAT_CHANCE: FLAT_CHANCE,
		FLAT_LEN_MIN: FLAT_LEN_MIN, FLAT_LEN_MAX: FLAT_LEN_MAX, FLAT_FADE: FLAT_FADE,
		RIDGE_ON: RIDGE_ON, RIDGE_UP: RIDGE_UP, RIDGE_AMP: RIDGE_AMP,
		RIDGE_WAVE: RIDGE_WAVE, RIDGE_SPEED: RIDGE_SPEED,

		// ★「場所」と「種」から必ず同じ 0〜1 を作る道具を、外にも貸す。
		//   ★背景の部品を置く `js/parts-draw.js` が使う。
		//     **2か所に同じ乱数を書くと、片方だけ直したときに世界が割れる**ので、正はここ1つ
		rand: hash,

		// 種を決める / 読む
		setSeed: function (n) { seed = (n | 0); return seed; },
		getSeed: function () { return seed; },
		// ★新しい世界に入る（走り出しに1回だけ呼ぶ）
		newSeed: function () {
			return this.setSeed(Math.floor(Math.random() * 100000));
		},

		// ★★地面の高さ。x = 世界のどこか（ドット）
		//   返す値 = **基準線から何ドット上か**（マイナスなら下）。★必ず整数
		groundAt: function (x) { return Math.round(heightRaw(x)); },
		// 丸める前の値（★なめらかさを測るためにテストが使う）
		groundRaw: heightRaw,
		// ★いまどれくらい平らか（0=丘のまま / 1=まっすぐな道の本体）
		flatnessAt: flatness,

		// ★遠景の稜線の高さ。同じく「基準線から何ドット上か」。★必ず整数
		//   ★ゆっくり流れるので、渡された場所を RIDGE_SPEED 倍して読む
		ridgeAt: function (x) {
			return Math.round(RIDGE_UP +
				waves(x * RIDGE_SPEED, RIDGE_WAVE, seed + 7777) * 2 * RIDGE_AMP);
		}
	};
})(typeof window !== "undefined" ? window : globalThis);
