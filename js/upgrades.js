	//       ★後半はちゃんと遠くなるので、天井に着かない（★2026-08-16 の上限なしと同じ狙い）
	//   ★★**急に高くなる段差が作れない形**にしてある（★倍率そのものを滑らかに動かす）
	var COST_EARLY = 1.45;   // ★★序盤、1段ごとに何倍か（★小さいほど、ぽんぽん買える）
	var COST_LATE  = 2.70;   // ★後半、1段ごとに何倍か（★大きいほど、1段が遠い）
	var COST_RAMP  = 12;     // ★何段かけて、序盤から後半へ移るか

	// ★★★次の1段の値段（★lv は 0 から）。★10 の倍数に丸める（画面で読みやすい）
	function costOf(u, lv) {
		var c = u.baseCost;
		for (var i = 0; i < lv; i++) c *= growthAt(u, i);
		return (c < 100) ? Math.round(c) : Math.round(c / 10) * 10;
	}

	// ★i 段目から i+1 段目へ、何倍になるか
	//   ★★`costGrowth` は「**後半の倍率**」として効く（★行ごとに変えられる）
	function growthAt(u, i) {
		var late = (u.costGrowth || COST_LATE);
		var t = Math.min(1, i / COST_RAMP);
		return COST_EARLY + (late - COST_EARLY) * t;
	}

	// ★そのレベルでの倍率（★Lv0 は 1 倍 ＝ 何も変わらない）
	function mulOf(u, lv) {
		return Math.pow(u.per, lv);
	}

