//   >   自分好みの強力な組み合わせを作る楽しさ、これにふります。」
//
// ■ ★このファイルで決まるもの
//     ・どんな強化があるか（★1行足せば1系統増える）
//     ・いくらか（`baseCost` と `costGrowth`）
//     ・どれくらい強くなるか（`per` ＝ 1レベルあたりの倍率）
//
//   ★**効かせ方（どこに掛けるか）は `js/ollie.js` が知っている。**
//     ここは「数字の表」だけ。★何でもできる仕組みを作らないこと
//     （ゲームを作る前にエンジンを作り始めることになるので）
//
// ■ ★★値段は「実測」から決めた（2026-08-15。★当てずっぽうではない）
//
//     1ラン ＝ 約15秒 / 約98m / ★**約159コイン**（Lv0・ふつうに遊んだとき）
//
//   → いちばん安いものを **150（＝約1ラン）** にしてある。
//     ★**1ラン走れば、何か1つは買える**（でも全部は買えない）
//
// ■ ★★全部を同じ方向に強くしないこと
//
//     SPEED   … 距離を増やす
//     JUMP    … 障害物を越えられるようにする
//     STAMINA … ランを長くする
//     MULT    … 稼ぐ速さを上げる
//     COIN    … 最後の取り分を増やす
//
//   ★役割が別々だから、「何を先に買うか」で**ビルドの差**が生まれる
//
// ■ ★数字の直し方
//     `baseCost`   … Lv1 の値段
//     `costGrowth` … 1レベル上がるごとに、値段が何倍になるか
//     `per`        … 1レベルごとに何倍強くなるか（★Lv3 なら per の3乗）
//
//   ★★**Lv4 以上に増やすのは、Lv3 までで「別のキャラクターになった」と
//     感じられることを確かめてから**（島さんの指定）。
//     ★感じられないなら、`maxLevel` を増やすのではなく **`per` を大きくする**
// ============================================================
(function (global) {
	"use strict";

	// ============================================================
	// ■■■ ① 強化の表（★1行足せば1系統増える）■■■
	// ============================================================
	//
	//   id       … 中で使う名前（★`js/ollie.js` がこの名前で効かせる）
	//   name     … 画面に出る名前（★フォントにある大文字だけ）
	//   maxLevel … 何段まで上げられるか。★★`null` = **上限なし**
	//
	//   ★★★2026-08-16、島さんの指定で**上限を無くした**:
	//     > 「大量のアップグレード、数値のインフレ、数ある強化要素からどれを選ぶかによって
	//     >   自分好みの強力な組み合わせを作る楽しさ」
	//
	//   ★実測で分かっていたこと: Lv3 までだと **24ラン・7.4分で買い切ってしまう**
	//
	//   ■ ★★あわせて直した数字（★全部**実測から**決めた。当てずっぽうではない）
	//
	//     `costGrowth` 2.2 → **2.7**
	//        観測 … 稼ぎは **1レベルあたり 2.44倍**で伸びるのに、値段は 2.2倍しか伸びない
	//               → ★**進むほど買いやすくなる**（＝加速して天井に着く）
	//        変更 … 稼ぎの伸び(2.44) × 1.12 ≒ **2.7**。★進むほど1レベルが遠くなる
	//
	//     `STAMINA` の per 1.25 → **1.08**
	//        観測 … 1.25 のままだと **Lv12 で1ランが 265秒（4.4分）**。★長すぎる
	//        変更 … 1.08 なら Lv12 で 50秒ほど
	//
	//     `JUMP` の per 1.20 → **1.06**、★`maxLevel` の 2 を外した
	//        観測 … 1.20 のままだと **Lv12 で技の拘束が 6.8秒**。★次が出せない
	//        変更 … 1.06 なら Lv12 で 1.5秒ほど。★上限を外しても暴れない
	//        ★★`maxLevel: 2` にしていた理由（拘束が伸びて逆効果）は、
	//          **Step 0 で障害物の間隔が技の長さに追従するようになった**ので消えた
	//   baseCost … Lv1 の値段
	//   costGrowth … 1段ごとに値段が何倍になるか
	//   per      … ★1段ごとに何倍強くなるか
	var UPGRADES = [
		// ★いちばん安い。**1ラン走れば買える**ので、最初の1個になりやすい
		{ id: "speed",   name: "SPEED",   maxLevel: null, baseCost: 150, costGrowth: 2.7, per: 1.15 },
		// ★★これを上げると**越えられる幅が広がる**（＝前は無理だった障害物を越せる）
		//
		// ★★★2026-08-16、上限を外した（★もとは `maxLevel: 2`）
		//   ★2 にしていた理由: 技の拘束 ＝ **技ぜんぶの時間 × jumpDurationMul** なので、
		//     上げるほど「次の技が出せるまで」が伸びて**逆効果**になっていた。
		//   ★★その理由は **Step 0 で消えた**（障害物の間隔が技の長さに追従するようになった）。
		//   ★あわせて `per` を 1.20 → 1.06 に下げてある（★上げすぎると拘束がまた伸びる）
		//
		//   ★★★JUMP は「安全」と引き換えに「稼ぎ」が減る:
		//     滞空が伸びる → 障害物の間隔も広がる → **出会う障害物が減る** → 倍率が伸びにくい
		//     ＝ ★これがビルドの選択になる（★安全を取るか、稼ぎを取るか）
		{ id: "jump",    name: "JUMP",    maxLevel: null, baseCost: 200, costGrowth: 2.7, per: 1.06 },
		// ★ランが長くなる ＝ 障害物に出会う数が増える ＝ 倍率も伸びる
		{ id: "stamina", name: "STAMINA", maxLevel: null, baseCost: 180, costGrowth: 2.7, per: 1.08 },
		// ★障害物を越えたときの倍率の伸びが大きくなる
		{ id: "mult",    name: "MULT",    maxLevel: null, baseCost: 250, costGrowth: 2.7, per: 1.40 },
		// ★最後にもらうコインが増える（★他とちがい、走りそのものは変わらない）
		{ id: "coin",    name: "COIN",    maxLevel: null, baseCost: 300, costGrowth: 2.7, per: 1.30 }
		// ★足すならここ。例:
		// { id: "magnet", name: "MAGNET", maxLevel: 3, baseCost: 400, costGrowth: 2.2, per: 1.2 },
	];

	// ============================================================
	// ■■■ ② 技のアンロック（★数値ではなく「できることが増える」）■■■
	// ============================================================
	//
	//   ★★**最初はオーリーだけ**（島さんの指定 2026-08-15）。
	//     キックフリップとポップは**買って覚える**。
	//
	//   ★これは Lv を上げるものではなく**買い切り**なので、上の表とは別にしてある
	//     （★数字が増えるのではなく、**できることが増える**タイプだから）
	//
	//   id … ★`js/frames.js` の技の名前を小文字にしたもの
	var UNLOCKS = [
		// ★★2.5ラン ぶん。**最初の「できることが増える」買い物**
		{ id: "kickflip", name: "KICKFLIP", cost: 400 },
		// ★4.4ラン ぶん
		{ id: "pop",      name: "POP",      cost: 700 }
	];

	// ============================================================
	// ここから下は仕組み（ふつうは触らない）
	// ============================================================

	// ★いまのレベルから「次の1段」の値段。★lv は 0 から
	//   ★10 の倍数に丸める（画面で読みやすいので）
	function costOf(u, lv) {
		var c = u.baseCost * Math.pow(u.costGrowth, lv);
		return Math.round(c / 10) * 10;
	}

	// ★そのレベルでの倍率（★Lv0 は 1 倍 ＝ 何も変わらない）
	function mulOf(u, lv) {
		return Math.pow(u.per, lv);
	}

	// ★id から表の1行を探す
	function find(id) {
		for (var i = 0; i < UPGRADES.length; i++) if (UPGRADES[i].id === id) return UPGRADES[i];
		return null;
	}

	function findUnlock(id) {
		for (var i = 0; i < UNLOCKS.length; i++) if (UNLOCKS[i].id === id) return UNLOCKS[i];
		return null;
	}

	global.DotUpgrades = {
		UPGRADES: UPGRADES,
		UNLOCKS: UNLOCKS,
		costOf: costOf,
		mulOf: mulOf,
		find: find,
		findUnlock: findUnlock
	};
})(typeof window !== "undefined" ? window : globalThis);
