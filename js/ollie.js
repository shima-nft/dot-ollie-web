			if (st.phase === "over") {
				// ★★★暗転しきるまでは効かない（2026-08-16）。
				//   ★ぶつかった勢いでタップしていると、**GAMEOVER を見ないまま**
				//     画面が切り替わってしまう（★何が起きたか分からない）
				if (!fadeDone()) return;
				toTitle();          // ★★島さんの指定「何か押したらタイトル画面へ」
				return;
			}
			// ★★★キャンプの選択（2026-08-16 / Phase D）。★買い物画面と**同じ操作**
			//   ★押した瞬間は構えるだけ。離したときに決める（★なぞりと取り合わないように）
