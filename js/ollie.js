	function groundRowAt(col) { return GROUND - WD.groundAt(worldX() + col); }

	// スケーターの足元の行（＝いま乗っている地面）
	function riderGroundRow() { return groundRowAt(RIDER_X + RIDER_FOOT); }

	// 次のコーンまでの間隔をランダムに引く
	// ★★1回の技のあいだに進む距離（★いまの速さとジャンプ倍率で**毎回計算する**）
	//   ★直書きしないこと。★島さんが `js/frames.js` のコマを速くしたら、ここも自動で追従する
	function trickTravelDots() {
		return FR.totalMs(POSES[poseIndex("OLLIE")].ms) * jumpDurationMul() / 1000 * curSpeed();
	}

	// ============================================================
	// ■■■ ★★★★拾えるコインの「一列」（2026-08-23 島さんの指定）■■■
	// ============================================================
	//
	//   > 島さん「コインは「弧」でなく横に整列にしてください。とりこぼしがあってもいい。
	//   >   そのほうがマグネットが生きる。」
	//
	//   ★★★**高さは島さんの跳躍の絵（`lifts`）から取る**（★直書きしない）。

	// ★★コインを置く高さ ＝ **オーリーがいちばん高く上がるところ**
	//   ★★★＝「跳んで届くいちばん上」。★島さんが絵を変えたら、ここも自動で追従する
	function pickLift() {
		var P = POSES[poseIndex("OLLIE")], best = 0;
		for (var i = 0; i < P.lifts.length; i++) if (P.lifts[i] > best) best = P.lifts[i];
		return best;
	}

	// ★1列のかたち … [{ dx（先頭からの横のずれ）, lift（足元の高さ）}, …]
	//   ★★**全部おなじ高さ**（★横に整列）。★等間隔に `PICK_N` 枚
	function pickRow() {
		var lift = pickLift();
		if (lift < PICK_MIN_LIFT) return [];      // ★低すぎるなら置かない（★走って取れる）
		var out = [];
		for (var k = 0; k < PICK_N; k++) out.push({ dx: k * PICK_STEP, lift: lift });
		return out;
	}

	// ★列の横幅（★障害物と重ねないための確かめに使う）
	function pickRowW(row) {
		return (row.length ? row[row.length - 1].dx : 0) + PICK_W;
	}

	// ============================================================
	// ★★★★列を「水平」に置く（2026-08-23 島さんの指摘）
	// ============================================================
	//
	//   > 島さん「コインが整列になっていないパターンがありました。
	//   >   おそらく地面と平行の高さに置かれているためと思われます。
	//   >   そのため、坂道にあるコインが整列でないです。平地は合格です。
	//   >   ジャンプで届く位置かつ水平においてください。そのほうが美しいです。」
	//
	//   ★★前は**1枚ずつ「その場所の地面」から高さを取っていた**ので、
	//     ★坂では列が**地面と平行に傾いて**いた。
	//   → ★★★**列の下でいちばん高い地面**を1つ選び、★そこから全部おなじ高さにする。
	//
	//   ★★「いちばん高い地面」を基準にするのが大事:
	//     ★★★どこか1枚でも地面に近づくと、★**走っているだけで拾えてしまう**。
	//     ★高いほうに合わせておけば、★列のどこでも「跳んで届く高さ」が保証される。
	//
	//   ★★★以後、コインは**画面の行（`y`）**で持つ（★地面からの高さでは持たない）。
	//     ★この作品はカメラが上下に動かないので、★**行は変わらない**
	function makeRow(x0) {
		var row = pickRow();
		if (!row.length) return [];
		// ★★列の下でいちばん高い地面（★行の数字が小さいほど高い）
		var top = Infinity;
		for (var i = 0; i < row.length; i++) {
			var gx = x0 + row[i].dx + Math.floor(PICK_W / 2);
			var gr = groundRowAt(gx);
			if (gr < top) top = gr;
		}
		var out = [];
		for (i = 0; i < row.length; i++) {
			// ★`y` = コインの**足元の行**（★全部おなじ ＝ 水平）
			out.push({ x: x0 + row[i].dx, y: top - 1 - row[i].lift });
		}
		return out;
	}

	// ★次の弧までの距離をランダムに引く（★種では決めない ＝ 覚えゲーにしない）
	function nextPickGap() {
		return PICK_GAP_MIN + Math.random() * (PICK_GAP_MAX - PICK_GAP_MIN);
	}

	// ★★1枚いくらか（★`PICK_SCALES` が 1 のときだけ COIN のレベルが効く）
	function pickValue() {
		return PICK_SCALES ? Math.max(1, Math.round(PICK_VALUE * upgMul("coin"))) : PICK_VALUE;
	}

	// ★★★障害物どうしの最小の間隔（→ 上の「欠陥」の説明）
	//   ★直書きの `CONE_GAP_MIN` は「下駄」として残す（★遅いときはこちらが効く）
	function coneGapMin() { return Math.max(CONE_GAP_MIN, trickTravelDots() * GAP_SAFETY); }
	function enemyGapMin() { return Math.max(ENEMY_GAP_MIN, trickTravelDots() * GAP_SAFETY); }

	function nextConeGap() {
		// ★ばらつきの幅（170-80）はそのまま。**下限だけが速さについてくる**
		return coneGapMin() + Math.random() * (CONE_GAP_MAX - CONE_GAP_MIN);
	}

	// ★丘の敵までの間隔をランダムに引く（★種で決めない ＝ 覚えゲーにしない）
	function nextEnemyGap() {
		return enemyGapMin() + Math.random() * (ENEMY_GAP_MAX - ENEMY_GAP_MIN);
	}

	// 次にプッシュするまでの待ち時間をランダムに引く
	function nextPushWait() {
		return PUSH_EVERY_MIN + Math.random() * (PUSH_EVERY_MAX - PUSH_EVERY_MIN);
	}

	// ★★走り出す前（enter / READY）の姿を進める
	//   ★**立ちをループするだけ。** たまに出るプッシュの時計は動かさない
	//     （世界が止まっているのに蹴り出したら変。プッシュは GO の瞬間から）
	function updateStandby(dt) {
		st.idleMs += dt * 1000;
		var P = POSES[st.idle];
		if (FR.frameAt(P.ms, st.idleMs) < 0) st.idleMs = 0;   // 繰り返す
	}

	// ★地上の姿を進める（技を出していないときだけ動く）
	//   ・ニュートラル … ずっとループ。たまにプッシュへ切り替わる
	//   ・プッシュ     … 1回流れたらニュートラルへ戻る
	function updateIdle(dt) {
		st.idleMs += dt * 1000;
		var P = POSES[st.idle];
		var done = (FR.frameAt(P.ms, st.idleMs) < 0);
		if (P.idle === "loop") {
			if (done) st.idleMs = 0;                       // 繰り返す
			st.nextPush -= dt;
			if (st.nextPush <= 0) {                        // ★たまにプッシュ
				st.idle = I_PUSH;
				st.idleMs = 0;
			}
		} else if (done) {                                 // "once" が終わった
			st.idle = I_STANDBY;
			st.idleMs = 0;
			st.nextPush = nextPushWait();
		}
	}

	// ------------------------------------------------------------
	// ■ ★★スタートの段を進める
	//   ready … 世界は止まっている（姿だけ動く）
	//   go    … もう動いている。文字が出ているだけ
	// ------------------------------------------------------------
	// ★どの段から始まるか（★0 にした段は飛ばす）
	function firstPhase() {
		if (ENTER_MS > 0) return "enter";
		if (READY_MS > 0) return "ready";
		return (GO_MS > 0) ? "go" : "play";
	}

	// ★世界が止まっている段か（enter と ready は止まっている）
	function isFrozen(phase) {
		return phase === "enter" || phase === "ready";
	}

	// ------------------------------------------------------------
	// ■ ★★走り出しの加速 —— いまトップスピードの何割で進んでいるか（0〜1）
	//   ★かける時間は**プッシュの絵の長さ**そのもの（直書きしない）
	// ------------------------------------------------------------
	function accelSpan() { return FR.totalMs(POSES[I_PUSH].ms); }

	function accelFactor() {
		if (!ACCEL_ON) return 1;
		var span = accelSpan();
		if (span <= 0) return 1;
		var t = st.speedMs / span;
		if (t >= 1) return 1;
		var s = t * t * (3 - 2 * t);            // 両端がゆるやかな曲線
		return ACCEL_START + (1 - ACCEL_START) * s;
	}

	function goNow() {
		st.phase = (GO_MS > 0) ? "go" : "play";
		st.phaseMs = 0;
		// ★★ここで走り出す ＝ プッシュ（蹴り出し）はこの瞬間から（島さん 2026-08-12）
		//   ★GO より前は世界が止まっているので、蹴っていたら変
		st.idle = I_PUSH;
		st.idleMs = 0;
		st.nextPush = nextPushWait();
		sound(990, 0.07);          // ★低→高で「始まる」
	}

	// ============================================================
	// ★★★★エンディングのあと、もう一度 READY / GO を出す（2026-08-23 島さんの指定）
	// ============================================================
	//
	//   > 島さん「エンディング後再スタートするとき再度READY/GO入れて。」
	//
	//   ★★**走り出しの加速もやり直す**（`speedMs = 0`）。
	//     ★エンディングのあいだ世界は止まっていたので、★★**そこから改めて走り出す**のが自然。
	//   ★★★走り出す前は**立って待つ**（★`enter`/`ready` と同じ。★蹴っていたら変）。
	//   ★段の進み方は `updatePhase()` に任せる（★2か所に持たない）
	function readyAgain() {
		st.speedMs = 0;             // ★★加速をやり直す（★止まったところから）
		st.idle = I_STANDBY;        // ★立って待つ
		st.idleMs = 0;
		if (READY_MS > 0) {
			st.phase = "ready";
			st.phaseMs = 0;
			sound(660, 0.06);       // ★READY の音（★はじめのときと同じ）
			return;
		}
		goNow();                    // ★READY を飛ばす設定なら、そのまま GO
	}

	function updatePhase(dt) {
		if (st.phase === "play") return;
		st.phaseMs += dt * 1000;
		if (st.phase === "enter") {
			if (st.phaseMs < ENTER_MS) return;
			// ★世界を見せる間が終わった → READY へ（READY が 0 なら そのまま GO）
			if (READY_MS > 0) {
				st.phase = "ready";
				st.phaseMs = 0;
				sound(660, 0.06);
			} else {
				goNow();
			}
		} else if (st.phase === "ready") {
			if (st.phaseMs >= READY_MS) goNow();
		} else if (st.phaseMs >= GO_MS) {
			st.phase = "play";
			st.phaseMs = 0;
		}
	}

	// ============================================================
	// ■■■ ★★当たり判定と転倒（2026-08-15 / Phase 2）■■■
	// ============================================================
	//
	//   ■ ★★縦は「足が地面についているコマ」だけ
	//     `lifts > 0`（＝島さんの絵の中で足が浮いている）あいだは**ぶつからない**。
	//     ★これが「越えられる幅」の実体。**物理の判定は作っていない**
	//
	//   ■ ★★横は「主役の足の位置」1点だけ（島さんの指定 2026-08-15）
	//     島さん「腕や頭がコーンに触れたから死亡、はゲームコアの検証を邪魔する」
	//     ★見たいのは「**跳べばコーンを越えられる**」ことだけ。
	//     ★足の位置は地面を読むのと**同じ列**を使う（2か所に持たない）
	//
	//   ★**障害物の外形を1ドットも太らせていない**（既存の決まり）
	// ============================================================
	// ★★★★二段目は「タップしたところ」から跳ぶ（2026-08-22 島さんの指定）
	// ============================================================
	//
	//   > 島さん「二段ジャンプの二回はタップしたところを基準としてほしい。
	//   >   そうじゃないとさらに高くとべない。」
	//
	//   ★★前 … 二段目も**足元 0（地面の高さ）から**絵が始まっていた
	//            → ★いったん落ちてから跳び直す形になり、**高くならなかった**
	//   ★★後 … ★★★**タップした瞬間の高さを「下駄」にして、その上に絵を重ねる**
	//
	//   ★★下駄は、二段目の絵が進むにつれて**まっすぐ 0 へ戻していく**。
	//     ★これが無いと、絵が終わった瞬間に**地面へストンと瞬間移動**して見える。
	//     ★★★物理は1つも足していません（★高さを決めているのは、いまも島さんの絵）。
	//
	//   ★`djBase` … タップした瞬間の足元の高さ（ドット）。★地上から跳ぶときは 0
	//   ★★★★2026-08-23、**ここを直しました**（島さんの指摘）:
	//     > 島さん「二段ジャンプの二回目がジャンプの途中でなく地面からとなっています。」
	//
	//     ★★★**下駄を `currentLift()` にしか足していなかった**のが原因でした。
	//       ★`currentLift()` は**当たり判定**にしか使われていません。
	//       ★★**絵を描くところ（`drawSkater()`）は、絵のコマだけで高さを決めていた**
	//         ので、★★★見た目は**まったく動いていませんでした**。
	//     → ★下駄を `djLift()` として切り出し、★★**描くところにも足しました**。

	// ★★絵がいちばん高くなる時点（ミリ秒）。★**絵から測る**＝直書きしない
	//   ★島さんがコマの長さを変えたら、ここも自動でついてくる
	function poseTopMs(P) {
		var best = -1, idx = 0;
		for (var i = 0; i < P.lifts.length; i++) {
			if (P.lifts[i] > best) { best = P.lifts[i]; idx = i; }
		}
		return FR.startMs(P.ms, idx);
	}

	// ★★二段目の「下駄」だけ（★絵そのものの跳躍は、コマの `y` に入っている）
	//
	//   ★★★**上がりきるまでは、タップした高さをそのまま保つ**（2026-08-23）。
	//     ★はじめは「技の進み具合で、まっすぐ減らす」形にしていたが、
	//       ★★**上がっている途中から減り始める**ので「さらに高く」が薄まっていた。
	//     ★★★いまは:
	//       タップした瞬間 … 下駄まるごと      ＝ **タップしたところが基準**
	//       絵の頂点       … 下駄 ＋ 絵の跳躍  ＝ ★★**いちばん高い**
	//       着地           … 0                 ＝ ★地面へ戻る（★瞬間移動しない）
	function djLift() {
		if (!st || !st.djBase || st.air < 0) return 0;
		var P = currentPose();
		var total = FR.totalMs(P.ms);
		var top = poseTopMs(P);              // ★絵がいちばん高くなるところ
		if (total <= top) return 0;
		if (st.air <= top) return st.djBase; // ★★上がりきるまでは、そのまま保つ
		// ★そのあと、着地までにまっすぐ 0 へ戻す
		var t = (st.air - top) / (total - top);
		return Math.round(st.djBase * (1 - Math.max(0, Math.min(1, t))));
	}

	function currentLift() {
		var P = currentPose();
		return P.lifts[currentFrame()] + djLift();
	}

