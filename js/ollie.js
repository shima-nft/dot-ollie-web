	//   → ★**「俺が上手くなった」ではなく「このビルドなら突破できる」**になる
	// ============================================================
	var PATTERN_ON = 1;      // 0 にすると障害物が出なくなる

	// ★その技の「越えられる幅」（ドット）。★表と速さから毎回計算する
	//   ★★これは **Lv0（アップグレード無し）の値**。障害物の大きさを決めるのに使う
	function clearDotsOf(name) {
		for (var i = 0; i < POSES.length; i++) {
			if (POSES[i].name !== name) continue;
			return Math.round(FR.airMs(POSES[i].ms, POSES[i].lifts) / 1000 * SPEED);
		}
		return 0;
	}

	// ★★★いま実際に越えられる幅（★アップグレードが乗ったあと）。
	//   空中の時間 × 速さ。★JUMP は時間を、SPEED は速さを伸ばす ＝ **掛け算になる**
	function curClearDots(name) {
		for (var i = 0; i < POSES.length; i++) {
			if (POSES[i].name !== name) continue;
			return Math.round(
				FR.airMs(POSES[i].ms, POSES[i].lifts) * jumpDurationMul() / 1000 * curSpeed());
		}
		return 0;
	}
	// ★その技の「拘束距離」（技を出してから次が出せるまでに進む距離）
	function lockDotsOf(name) {
		for (var i = 0; i < POSES.length; i++) {
			if (POSES[i].name !== name) continue;
			return Math.round(FR.totalMs(POSES[i].ms) / 1000 * SPEED);
		}
		return 0;
	}
	// ★★★「Lv0 のときに越えられる幅」＝ 障害物の大きさを決める基準
	//   ★★アップグレードが乗る前の値なので、**世界の側は永久に変わらない**。
	//     だからこそ「前は越えられなかったコーンが越えられた」が起きる
	//
	//   ★★★**ここを `curSpeed()` に変えないこと**（2026-08-15 / Phase B）。
	//     変えると**障害物が自分に合わせて大きくなり**、
	//     「前は越えられなかったものが越えられた」が**永久に起きなくなる**。
	//
	//       SPEED を上げる → プレイヤーが速くなる
	//       → 同じ障害物を以前より短時間で通過する
	//       → ★★**障害物そのものは大きくならない**
	var BASE_CLEAR = clearDotsOf("OLLIE");

	// ★その幅に収まるコーンの個数（★1個ぶん余裕を残す）
	function conesForDots(dots) {
		return Math.max(1, Math.floor((dots - CONE_W) / CONE_W));
	}

	// ============================================================
	// ■ ★★★「多くても、ギリギリ越えられる幅」（★島さんの指定 2026-08-20）
	// ============================================================
	//
	//   > 島さん「コーンは多くてもギリギリ越えられる幅に設定して。どのレベルでも。
	//   >         たくさん並べる時の話だよ。頻度はいまのままでよい」
	//
	//   ★★並んだコーンの塊は、**いま自分が1回の技で覆いきれる幅**を超えない。
	//     覆いきれる幅 ＝ `curClearDots("OLLIE")`（空中の時間 × ★いまの速さ）。
	//
	//   ★★★これは**天井であって、下限ではない**。
	//     ★パターンが元々もっている個数より**増やす方向には一切効かない**。
	//     → だから「強くなると障害物も大きくなる」にはならない
	//       （★`BASE_CLEAR` は Lv0 のまま。★ここは今までどおり触っていない）。
	//
	//   ★`CLEAR_MARGIN` ＝「ギリギリ」の余裕（ドット）。
	//     ★n個ぶんの幅は `n * CONE_W - 1` ドットなので、
	//       **覆いきれる幅 − 余裕** に収まる最大の個数を出す。
	//     ★0 にすると**1ドットの狂いも許されない**タイミングになる。
	//       6 ＝ Lv0 の速さ（70ドット/秒）で **約86ミリ秒ぶんの猶予**。
	//
	//   ★★頻度（`coneGapMin()` / `nextConeGap()`）には**触っていない**
	//     ＝ 島さんの「頻度はいまのままでよい」。
	//
	//   ⚠ ★★★この天井が入ったことで**変わったこと**（★島さんの判断待ち）:
	//     ・「D 広い」は Lv0 でも越えられるようになった（★越えられない壁が消えた）
	//     ・距離で太る仕組み（`TIER_*`）も、この天井までしか効かなくなった
	//     ★戻すときは `CLEAR_LIMIT_ON = 0`（★1行で昔どおりに戻る）
	// ============================================================
	var CLEAR_LIMIT_ON = 1;   // ★0 = 昔どおり（越えられない幅も出る）
	var CLEAR_MARGIN   = 6;   // ★「ギリギリ」の余裕（ドット）

	// ★★いまの自分が1回の技で覆いきれる、コーンの個数の上限
	function maxConesNow() {
		return Math.max(1,
			Math.floor((curClearDots("OLLIE") - CLEAR_MARGIN + 1) / CONE_W));
	}

	// ★★パターンの表。★`ns` = コーンの個数の並び（★`at` は距離から作る）
	//   ★★`at`（2個目以降の置き場所）を**表に直書きしない**。
	//     直書きすると、下の「距離で太らせる」で**1個目と重なる**（太ったぶんを足し忘れる）
	function buildPatterns() {
		var nNarrow = conesForDots(BASE_CLEAR * 0.55);   // ★Lv0 でも余裕
		var nMid    = conesForDots(BASE_CLEAR * 1.00);   // ★Lv0 でぎりぎり
		var nWide   = conesForDots(BASE_CLEAR * 1.80);   // ★★Lv0 では越えられない
		// ★★★`gap` は「**空いている幅**」（★2026-08-16 に直した）
		//   もとの表は `at: 53`（＝パターンの先頭からの位置）を直書きしていた。
		//   ★下の `patternAt()` で `at` を作り直すとき、うっかり
		//     「1個目の幅 ＋ 53」にしてしまい、**空きが 44 → 53 に広がっていた**
		//     ＝ 島さんに黙って **パターンC が少し易しくなっていた**（回帰）。
		//   → ★`gap` を最初から「空いている幅」にして、意味を1つに固定する
		var gap = Math.round(BASE_CLEAR * 1.3) - CONE_W;   // ★空き = 44ドット
		return [
			{ name: "A 狭い", ns: [nNarrow],          gap: gap },
			{ name: "B 中",   ns: [nMid],             gap: gap },
			{ name: "C 連続", ns: [nNarrow, nNarrow], gap: gap },
			// ★★D は Lv0 では越えられない。**アップグレードで越えられるようになる壁**
			{ name: "D 広い", ns: [nWide],            gap: gap }
		];
	}
	var PATTERNS = buildPatterns();

