	//     ★ラン終了の画面から見たときは `START`（＝タップ1回で即もう一回）のまま
	function shopRows() {
		var opened = !!(st && st.shopOpen);
		var rows = [{ kind: "start", name: opened ? "CLOSE" : "START" }];
		if (!UP) return rows;
		UP.UPGRADES.forEach(function (u) {
			var lv = upgLevel(u.id);
			rows.push({
				kind: "upg", id: u.id, name: u.name, lv: lv, max: u.maxLevel,
				// ★★`maxLevel: null` = 上限なし。★そのときは必ず次の値段が出る
				cost: (u.maxLevel !== null && lv >= u.maxLevel) ? 0 : UP.costOf(u, lv)
			});
		});
		UP.UNLOCKS.forEach(function (u) {
			rows.push({
				kind: "unlock", id: u.id, name: u.name,
				got: !!unlocked[u.id], cost: u.cost
			});
		});
		// ★★★使うと無くなるもの（2026-08-22）。★何本でも買える ＝ `got` を持たない
		(UP.ITEMS || []).forEach(function (u) {
			rows.push({
				kind: "item", id: u.id, name: u.name,
				have: bagCount(u.id), maxHave: (u.maxHave || 1),
				// ★★★値段は「**次に買う値段**」（★買うたびに10倍）
				cost: itemCost(u)
			});
		});
		return rows;
	}

	// ★その行が買えるか（★買えないものは暗く出す）
	function canBuy(r) {
		if (r.kind === "start") return true;
		// ★★★使うと無くなるもの（2026-08-22 島さんの指定）:
		//   ・★**持てるのは 1 本まで**（★持っているあいだは買えない）
		//   ・★★値段は買うたびに10倍（★`cost` にはもう次の値段が入っている）
		if (r.kind === "item") return r.have < r.maxHave && coins >= r.cost;
		// ★★上限なし（`max === null`）なら、レベルでは止めない
		return !r.got && coins >= r.cost;
	}

	// ★★決定を押したとき。★買えたら true
	function shopPick() {
		var rows = shopRows();
		var r = rows[Math.max(0, Math.min(rows.length - 1, st.shopSel))];
		if (!r || r.kind === "start") return false;
		if (!canBuy(r)) { sound(180, 0.06); return false; }   // ★買えない音
		if (r.kind === "upg") {
			coins -= r.cost;
			upgLv[r.id] = (upgLv[r.id] || 0) + 1;
		} else if (r.kind === "item") {
			// ★★使うと無くなるもの。★★★**買った回数**も数える（★次の値段が10倍になる）
			coins -= r.cost;
			bag[r.id] = bagCount(r.id) + 1;
			buys[r.id] = buyCount(r.id) + 1;
		} else {
			coins -= r.cost;
			unlocked[r.id] = true;
		}
		saveCoins();
		saveUpg();
		buySound();                                            // ★★★買えた音（★脳汁）
		return true;
	}

	function shopMove(d) {
		var n = shopRows().length;
		st.shopSel = (st.shopSel + d + n) % n;
		sound(880, 0.03);
	}

	// ★★いま選んでいる行を決める（★呼ぶのは「指を離したとき」＝ `inputUp`）
	function shopDecide() {
		var rows = shopRows();
		if (rows[st.shopSel] && rows[st.shopSel].kind === "start") {
			// ★★ショップボタンから開いていたら「閉じる」／ラン終了の画面なら「もう一回」
			if (st.shopOpen) { global.DotOllie.toggleShop(); return; }
			restart();
			return;
		}
		shopPick();
	}

