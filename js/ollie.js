	var TIER_ON  = 1;     // ★0 にすると、昔どおり「ずっと同じ幅」に戻る
	var TIER_M   = 250;   // ★何メートルごとに1段きつくなるか
	var TIER_ADD = 1;     // ★1段ごとにコーンが何個増えるか（1個 = CONE_W = 9ドット）
	// ★★増える上限。★D が最大 63 + 9×14 = **189px**（画面の79%）。
