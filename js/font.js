	var SPACING = 1;

	// text を ctx に (x,y) 原点・1ドット=1px で描く。color は塗り色
	function drawText(ctx, text, x, y, color) {
		ctx.fillStyle = color;
		for (var i = 0; i < text.length; i++) {
			var g = GLYPHS[text[i]] || GLYPHS[" "];
			var gx = x + i * (GLYPH_W + SPACING);
			for (var row = 0; row < GLYPH_H; row++) {
				for (var col = 0; col < GLYPH_W; col++) {
					if (g[row][col] === "#") {
						ctx.fillRect(gx + col, y + row, 1, 1);
					}
				}
			}
		}
	}

	function textWidth(len) {
		return len * (GLYPH_W + SPACING) - SPACING;
	}

