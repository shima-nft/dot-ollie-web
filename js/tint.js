// ============================================================
// ★★ 距離と時間帯の「半透明フィルター」 —— 島さんの持ち場 ★★
// ============================================================
//
//   島さん（2026-08-11）:
//   > 空気遠近法を「26色だけで全部表現する」のではなく、
//   > 「26色の絵＋半透明レイヤー」で作る。
//   > 26色＝元絵の制約 / 半透明レイヤー＝距離・時間帯を表現するエフェクト
//   > と役割を分けるのが最適だと思います。
//   > これは昼・夕方・夜・雪・霧などの環境変化にも
//   > 同じ背景素材を使い回せるという大きなメリットがあります。
//
// ■ ★★ここが「奥ほど淡く」を作っている場所です
//
//   絵そのものは**どの距離でも同じ26色**で描いてかまいません。
//   遠く見せるのは、この表に書いた**うすい色を上からかぶせる量**です。
//
//     最遠景 …… いちばん多くかぶせる（＝いちばん淡い）
//     前景   …… 何もかぶせない（＝いちばん濃く鮮やか）
//
// ■ ★★仕組みの話（大事なので1つだけ）
//
//   実際には「画面に半透明の板を重ねて」いません。
//   **色ひとつひとつを、あらかじめ混ぜた色に置き換えて**います。
//   見た目はまったく同じで、こちらのほうが:
//
//     ・**同じところに二重にかからない**（重なった部品でも1回だけ）
//     ・速い（毎コマ画面いっぱいを塗り直さない）
//     ・機械が数字で確かめられる（テストが「淡くなりすぎ」を見張れる）
//
// ■ 書き方
//
//     フィルター名: [ [色の番号, かぶせる％], ... ]
//
//   ★色の番号は `js/palette.js` の番号（26色）。★％は 0〜100。
//   ★1つのマスに**色を2つ重ねられます**（島さんの「青紫＋白」のため）。上から順にかかります。
//   ★**空にすれば「何もかぶせない」**。
// ============================================================
(function (global) {
	"use strict";

	var GB = global.DotPalette.COLORS;

	// ============================================================
	// ■■■ ★いま使う時間帯（1つだけ）■■■
	// ============================================================
	//   ★昼→夕方→夜の**自動切り替えはまだ入れていません**（島さんの指定）。
	//     ここを "NIGHT" に書き換えると、夜の見え方をそのまま試せます
	var FIXED_TIME = "DAY";

	// ============================================================
	// ■■■ ★★フィルターの表 —— 触るのはここだけ ■■■
	// ============================================================
	//   ★フィルター名（far3 / far2 / far1）は `js/parts.js` の層の表から呼ばれます。
	//     層を増やしたら、ここにも同じ名前で1行足してください
	var TIMES = {

		// ---- 昼 ----------------------------------------------------
		//   島さんの指定: 最遠景=白＋水色 / 遠景=白 / 中景=ごく薄い水色 / 前景=なし
		DAY: {
			far3: [[15, 30], [24, 10]],   // 白30% ＋ 水色10%
			far2: [[15, 20]],             // 白20%
			far1: [[24, 10]]              // ごく薄い水色10%
		},

		// ---- 夜（★まだ使っていません。FIXED_TIME を "NIGHT" にすると試せます）----
		//   島さんの指定: 最遠景=青紫＋白 / 遠景=青紫 / 中景=紺 / 前景=なし
		NIGHT: {
			far3: [[9, 45], [15, 10]],    // 藤色(青紫)45% ＋ 白10%
			far2: [[9, 35]],              // 藤色(青紫)35%
			far1: [[7, 25]]               // 濃紺25%
		}

		// ★あとで足す場所: SNOW（雪）/ FOG（霧）/ EVENING（夕方）
		//   ★表を1つ足すだけで入ります。**絵は1枚も描き直しません**（これが島さんの設計の利点）
	};

	// ============================================================
	// 以下は仕組み。ふつうは触らない
	// ============================================================

	function hexToRgb(h) {
		h = String(h).replace("#", "");
		return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
	}

	function rgbToHex(v) {
		return "#" + v.map(function (n) {
			return ("0" + Math.max(0, Math.min(255, Math.round(n))).toString(16)).slice(-2);
		}).join("");
	}

	// 1色に、フィルターを上から順にかける
	function blend(hex, recipe) {
		if (!recipe || !recipe.length) return hex;
		var c = hexToRgb(hex);
		for (var i = 0; i < recipe.length; i++) {
			var t = hexToRgb(GB[recipe[i][0]]), a = recipe[i][1] / 100;
			for (var k = 0; k < 3; k++) c[k] = c[k] * (1 - a) + t[k] * a;
		}
		return rgbToHex(c);
	}

	var cache = {};

	global.DotTint = {
		TIMES: TIMES,
		FIXED_TIME: FIXED_TIME,
		time: FIXED_TIME,

		// いまの時間帯を変える（★時間帯の自動切り替えを作るときの入口）
		setTime: function (name) {
			if (!TIMES[name]) return false;
			this.time = name;
			cache = {};
			return true;
		},

		// フィルター1つ分の中身（無ければ null）
		recipe: function (filterName) {
			if (!filterName) return null;
			var t = TIMES[this.time];
			return (t && t[filterName]) ? t[filterName] : null;
		},

		// ★★26色ぜんぶを「かぶせたあとの色」に置き換えた表を作る。
		//   ★層ごとに1回だけ作れば、あとは色を引くだけ ＝ 二重がけが起きようがない
		tableFor: function (filterName) {
			var key = this.time + "/" + (filterName || "-");
			if (cache[key]) return cache[key];
			var r = this.recipe(filterName);
			var out = GB.map(function (c) { return blend(c, r); });
			cache[key] = out;
			return out;
		},

		// テストが使う（1色だけ確かめたいとき）
		blendOne: blend
	};
})(typeof window !== "undefined" ? window : globalThis);
